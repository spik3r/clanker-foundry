package tui

import (
	"bytes"
	"crypto/sha256"
	"embed"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"go/format"
	"sort"
	"strconv"
	"strings"
	"text/template"
)

//go:embed templates/*
var sources embed.FS

// moduleOnly lists the template outputs that exist only in module mode.
var moduleOnly = map[string]bool{"go.mod": true, "go.sum": true, "demo_main.go": true}

// Compile emits an importable package, never runs it, and never performs I/O.
// Details retain presentation order; declarations are normalized by field ID.
func Compile(m Model) (map[string][]byte, error) {
	if err := m.Validate(); err != nil {
		return nil, err
	}
	m = m.canonical()
	m.Fields = append([]Field(nil), m.Fields...)
	sort.Slice(m.Fields, func(i, j int) bool { return m.Fields[i].ID < m.Fields[j].ID })
	canonical, err := json.MarshalIndent(m, "", "  ")
	if err != nil {
		return nil, err
	}
	sum := sha256.Sum256(canonical)
	digestHex := hex.EncodeToString(sum[:])
	files := map[string][]byte{"model.json": append(canonical, '\n')}
	entries, err := sources.ReadDir("templates")
	if err != nil {
		return nil, err
	}
	for _, entry := range entries {
		name := strings.TrimSuffix(entry.Name(), ".tmpl")
		if m.PackageMode() && moduleOnly[name] {
			continue
		}
		if name == "demo_main.go" {
			name = "cmd/demo/main.go"
		}
		raw, err := sources.ReadFile("templates/" + entry.Name())
		if err != nil {
			return nil, err
		}
		tmpl, err := template.New(name).Delims("[[[", "]]]").Funcs(template.FuncMap{"quote": strconv.Quote, "hintIDs": KeyHintIDs}).Option("missingkey=error").Parse(string(raw))
		if err != nil {
			return nil, fmt.Errorf("template %s: %w", name, err)
		}
		var out bytes.Buffer
		if err := tmpl.Execute(&out, m); err != nil {
			return nil, err
		}
		content := out.Bytes()
		if strings.HasSuffix(name, ".go") {
			content = append([]byte(fmt.Sprintf("// Code generated by %s %s from model %s. DO NOT EDIT.\n\n", GeneratorID, GeneratorVersion, digestHex)), content...)
			content, err = format.Source(content)
			if err != nil {
				return nil, fmt.Errorf("format %s: %w", name, err)
			}
		}
		files[name] = content
	}
	manifest, err := manifestBytes(digestHex, files)
	if err != nil {
		return nil, err
	}
	files[ManifestName] = manifest
	return files, nil
}
