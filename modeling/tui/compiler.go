package tui

import (
	"bytes"
	"crypto/sha256"
	"embed"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"go/format"
	"sort"
	"strconv"
	"strings"
	"text/template"
)

//go:embed templates/*
var sources embed.FS

// Compile emits an importable package, never runs it, and never performs I/O.
// Details retain presentation order; declarations are normalized by field ID.
func Compile(m Model) (map[string][]byte, error) {
	if err := m.Validate(); err != nil {
		return nil, err
	}
	m.Fields = append([]Field(nil), m.Fields...)
	sort.Slice(m.Fields, func(i, j int) bool { return m.Fields[i].ID < m.Fields[j].ID })
	canonical, err := json.MarshalIndent(m, "", "  ")
	if err != nil {
		return nil, err
	}
	digest := sha256.Sum256(canonical)
	files := map[string][]byte{"model.json": append(canonical, '\n')}
	entries, err := sources.ReadDir("templates")
	if err != nil {
		return nil, err
	}
	for _, entry := range entries {
		name := strings.TrimSuffix(entry.Name(), ".tmpl")
		if name == "demo_main.go" {
			name = "cmd/demo/main.go"
		}
		raw, err := sources.ReadFile("templates/" + entry.Name())
		if err != nil {
			return nil, err
		}
		tmpl, err := template.New(name).Delims("[[[", "]]]").Funcs(template.FuncMap{"quote": strconv.Quote}).Option("missingkey=error").Parse(string(raw))
		if err != nil {
			return nil, fmt.Errorf("template %s: %w", name, err)
		}
		var out bytes.Buffer
		if err := tmpl.Execute(&out, m); err != nil {
			return nil, err
		}
		content := out.Bytes()
		if strings.HasSuffix(name, ".go") {
			content = append([]byte("// Code generated by Foundry record-browser/v1; DO NOT EDIT.\n\n"), content...)
			content, err = format.Source(content)
			if err != nil {
				return nil, fmt.Errorf("format %s: %w", name, err)
			}
		}
		files[name] = content
	}
	type artifact struct {
		Path   string `json:"path"`
		SHA256 string `json:"sha256"`
	}
	names := make([]string, 0, len(files))
	for name := range files {
		names = append(names, name)
	}
	sort.Strings(names)
	artifacts := make([]artifact, 0, len(names))
	for _, name := range names {
		sum := sha256.Sum256(files[name])
		artifacts = append(artifacts, artifact{name, hex.EncodeToString(sum[:])})
	}
	trace := struct {
		Format      string     `json:"format"`
		Profile     string     `json:"profile"`
		ModelSHA256 string     `json:"modelSha256"`
		Artifacts   []artifact `json:"artifacts"`
	}{"tui-trace/v1", Profile, hex.EncodeToString(digest[:]), artifacts}
	raw, err := json.MarshalIndent(trace, "", "  ")
	if err != nil {
		return nil, err
	}
	files["trace.json"] = append(raw, '\n')
	return files, nil
}
