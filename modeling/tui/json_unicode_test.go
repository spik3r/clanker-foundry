const surrogateError = "unpaired surrogate escape in JSON"

func unicodeModel(t *testing.T, text string) []byte {
	t.Helper()
	m := exampleModel(t)
	m.Title = "UNICODE"
	raw, err := json.Marshal(m)
	if err != nil {
		t.Fatal(err)
	}
	return bytes.Replace(raw, []byte(`"UNICODE"`), []byte(`"`+text+`"`), 1)
}

func TestDecodeUnicodeRefusals(t *testing.T) {
	for _, text := range []string{`\ud800`, `\udbff`, `\udc00`, `\udfff`, `\udc00\ud800`, `\ud800x`, `\ud800\u0041`, `\ud800\ud800`, `\ud800\\udc00`, `\ud800\udc00\udfff`} {
		t.Run(text, func(t *testing.T) {
			model := unicodeModel(t, text)
			nestedModel := bytes.Replace(exampleBytes(t), []byte(`"Identifier"`), []byte(`"`+text+`"`), 1)
			for _, raw := range [][]byte{model, nestedModel, bytes.Replace(model, []byte(`"title"`), []byte(`"`+text+`"`), 1)} {
				if _, err := Decode(raw); err == nil || err.Error() != surrogateError {
					t.Errorf("model Unicode refusal = %v", err)
				}
			}
			for _, pair := range [][2]string{
				{`"Alpha"`, `"` + text + `"`},
				{`"ID": "a"`, `"` + text + `": "a"`},
				{`"requirement": "Enter shows details."`, `"requirement": "` + text + `"`},
				{`"key": "j"`, `"text": "` + text + `"`},
				{`"selected": "b"`, `"filter": "` + text + `"`},
				{`"Name: Beta"`, `"` + text + `"`},
				{`"steps"`, `"` + text + `"`},
			} {
				raw := strings.Replace(baseCases, pair[0], pair[1], 1)
				if raw == baseCases {
					t.Fatal("test replacement did not match")
				}
				if _, err := DecodeCases([]byte(raw)); err == nil || err.Error() != surrogateError {
					t.Errorf("cases Unicode refusal = %v", err)
				}
			}
		})
	}
}

func TestDecodeUnicodePreservesValidInput(t *testing.T) {
	for _, tc := range []struct{ escaped, literal string }{
		{`\ud83d\ude00`, "😀"}, {`\uD800\uDC00`, "𐀀"}, {`\udbff\udfff`, "\U0010ffff"},
		{`\ufffd`, "�"}, {"�", "�"}, {`\\ud800`, `\ud800`}, {`\\\"\ud83d\ude00\/`, "\\\"😀/"},
	} {
		t.Run(tc.escaped, func(t *testing.T) {
			raw := unicodeModel(t, tc.escaped)
			m, err := Decode(raw)
			if err != nil {
				t.Fatal(err)
			}
			if m.Title != tc.literal {
				t.Fatalf("title = %q, want %q", m.Title, tc.literal)
			}
			literal, err := json.Marshal(m)
			if err != nil {
				t.Fatal(err)
			}
			escapedBuild, err := Build(raw)
			if err != nil {
				t.Fatal(err)
			}
			literalBuild, err := Build(literal)
			if err != nil {
				t.Fatal(err)
			}
			if !reflect.DeepEqual(escapedBuild.Files, literalBuild.Files) {
				t.Fatal("escape spelling changed digest or generated bytes")
			}
			craw := strings.Replace(baseCases, `"Alpha"`, `"`+tc.escaped+`"`, 1)
			c, err := DecodeCases([]byte(craw))
			if err != nil {
				t.Fatal(err)
			}
			if c.Records["Main"][0]["Name"] != tc.literal {
				t.Fatal("record text changed")
			}
		})
	}
}

func TestDecodeUnicodePreservesSyntaxErrors(t *testing.T) {
	for _, text := range []string{`\u`, `\ud80`, `\uxxxx`, `\ud800\u`, `\q`, `abc\`} {
		for _, raw := range [][]byte{unicodeModel(t, text), []byte(strings.Replace(baseCases, `"Alpha"`, `"`+text+`"`, 1))} {
			var syntax *json.SyntaxError
			if err := json.Unmarshal(raw, new(any)); err == nil {
				t.Fatal("test input has valid syntax")
			} else {
				syntax = err.(*json.SyntaxError)
			}
			var err error
			if bytes.Contains(raw, []byte(CasesFormat)) {
				_, err = DecodeCases(raw)
			} else {
				_, err = Decode(raw)
			}
			if err == nil || err.Error() != syntax.Error() {
				t.Fatalf("syntax error = %v, want %v", err, syntax)
			}
		}
	}
}
