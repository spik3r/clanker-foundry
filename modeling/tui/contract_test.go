func TestManifestBindsEveryFileAndHeaders(t *testing.T) {
	files, err := Compile(sampleModel(t))
	if err != nil {
		t.Fatal(err)
	}
	if _, ok := files["trace.json"]; ok {
		t.Fatal("trace.json is no longer emitted")
	}
	var mf struct {
		ManifestVersion string
		Profile         string
		Generator       struct{ ID, Version, Toolchain string }
		Model           struct{ CanonicalSHA256 string }
		Files           []struct {
			Path   string
			SHA256 string
			Bytes  int
		}
	}
	dec := json.NewDecoder(bytes.NewReader(files[ManifestName]))
	dec.DisallowUnknownFields()
	if err := dec.Decode(&mf); err != nil {
		t.Fatal(err)
	}
	if mf.ManifestVersion != "foundry-generator-manifest/v1" || mf.Profile != Profile ||
		mf.Generator.ID != "tuic" || mf.Generator.Version != "1.5.0" || mf.Generator.Toolchain != "go1.27.4" {
		t.Fatalf("manifest fields: %+v", mf)
	}
	if len(mf.Files) != len(files)-1 {
		t.Fatal("manifest incomplete")
	}
	prev := ""
	for _, a := range mf.Files {
		raw, ok := files[a.Path]
		if !ok || a.Path <= prev || a.Path == ManifestName {
			t.Fatalf("invalid manifest path %q", a.Path)
		}
		prev = a.Path
		sum := sha256.Sum256(raw)
		if a.SHA256 != hex.EncodeToString(sum[:]) || a.Bytes != len(raw) {
			t.Fatal("artifact mismatch")
		}
	}
	sum := sha256.Sum256(bytes.TrimSuffix(files["model.json"], []byte("\n")))
	digest := hex.EncodeToString(sum[:])
	if mf.Model.CanonicalSHA256 != digest {
		t.Fatal("model identity mismatch")
	}
	header := "// Code generated by tuic 1.5.0 from model " + digest + ". DO NOT EDIT.\n"
	goFiles := 0
	for name, raw := range files {
		if strings.HasSuffix(name, ".go") {
			goFiles++
			if !bytes.HasPrefix(raw, []byte(header)) {
				t.Fatalf("%s lacks the generated header", name)
			}
		}
	}
	if goFiles == 0 {
		t.Fatal("no Go files emitted")
	}
}

func TestCanonicalDigestIgnoresWhitespaceAndFieldOrderButNotDetails(t *testing.T) {
	raw, err := os.ReadFile("examples/browser.json")
	if err != nil {
		t.Fatal(err)
	}
	base, err := Build(raw)
	if err != nil {
		t.Fatal(err)
	}
	var generic map[string]any
	if err := json.Unmarshal(raw, &generic); err != nil {
		t.Fatal(err)
	}
	fields := generic["fields"].([]any)
	fields[0], fields[len(fields)-1] = fields[len(fields)-1], fields[0]
	reordered, _ := json.MarshalIndent(generic, "\t", "   ")
	got, err := Build(reordered)
	if err != nil {
		t.Fatal(err)
	}
	if !reflect.DeepEqual(base.Files, got.Files) {
		t.Fatal("whitespace or field order changed output")
	}
	if base.Identity == got.Identity {
		t.Fatal("source digest should differ")
	}
	details := generic["details"].([]any)
	details[0], details[1] = details[1], details[0]
	swapped, _ := json.Marshal(generic)
	other, err := Build(swapped)
	if err != nil {
		t.Fatal(err)
	}
	if bytes.Equal(base.Files[ManifestName], other.Files[ManifestName]) {
		t.Fatal("details order must change the canonical digest")
	}
}
