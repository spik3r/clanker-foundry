// solidOf returns the model text with "target": "solid" added.
func solidOf(t testing.TB, raw string) string {
	t.Helper()
	var m map[string]json.RawMessage
	if err := json.Unmarshal([]byte(raw), &m); err != nil {
		t.Fatal(err)
	}
	m["target"] = json.RawMessage(`"solid"`)
	b, err := json.Marshal(m)
	if err != nil {
		t.Fatal(err)
	}
	return string(b)
}

func generate(t testing.TB, raw string) contract.Generated {
	t.Helper()
	g, err := Profiler{}.Generate([]byte(raw), testGen)
	if err != nil {
		t.Fatal(err)
	}
	return g
}

func renderSolid(t testing.TB, raw string) string {
	t.Helper()
	return string(generate(t, raw).Files[FileJSX])
}

// literalRE matches one JavaScript double-quoted string literal.
var literalRE = regexp.MustCompile(`"(?:[^"\\\n]|\\.)*"`)

// outsideLiterals returns the source with every string literal emptied.
func outsideLiterals(src string) string { return literalRE.ReplaceAllString(src, `""`) }

