// TestSolidParsesAsJSX runs the output through esbuild's JSX parser when Node
// and esbuild are installed; otherwise it skips.
func TestSolidParsesAsJSX(t *testing.T) {
	node, err := exec.LookPath("node")
	if err != nil {
		t.Skip("node is not installed; the JSX parse was not checked")
	}
	var mod string
	for _, d := range esbuildDirs() {
		if _, err := os.Stat(filepath.Join(d, "esbuild", "package.json")); err == nil {
			if abs, err := filepath.Abs(d); err == nil {
				mod = abs
				break
			}
		}
	}
	if mod == "" {
		t.Skip("esbuild is not installed (set SOLID_NODE_MODULES to a node_modules directory that has it); the JSX parse was not checked")
	}
	script := `const esbuild = require(process.argv[1] + "/esbuild");
const fs = require("fs");
for (const f of process.argv.slice(2)) {
  esbuild.transformSync(fs.readFileSync(f, "utf8"), { loader: "jsx", jsx: "preserve", logLevel: "silent" });
}`
	dir := t.TempDir()
	var files []string
	write := func(name, text string) {
		p := filepath.Join(dir, name)
		if err := os.WriteFile(p, []byte(text), 0o644); err != nil {
			t.Fatal(err)
		}
		files = append(files, p)
	}
	for _, name := range exampleModels {
		write(name+".jsx", renderSolid(t, solidOf(t, example(t, name))))
	}
	write("hostile.jsx", renderSolid(t, hostileSolid(t, true)))
	cmd := exec.Command(node, append([]string{"-e", script, mod}, files...)...)
	cmd.Env = []string{}
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("JSX does not parse: %v\n%s", err, out)
	}
}
