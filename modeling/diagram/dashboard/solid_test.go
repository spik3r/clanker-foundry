var (
	forbiddenSolid = []*regexp.Regexp{
		regexp.MustCompile(`innerHTML`), regexp.MustCompile(`dangerouslySetInnerHTML`),
		regexp.MustCompile(`\bfetch\b`), regexp.MustCompile(`(?i)https?:`), regexp.MustCompile(`//[a-z0-9.-]+\.[a-z]`),
		regexp.MustCompile(`\bon[A-Z][A-Za-z]*\s*=`), regexp.MustCompile(`\bon[a-z]+\s*=`),
		regexp.MustCompile(`\beval\b`), regexp.MustCompile(`\bFunction\s*\(`), regexp.MustCompile(`\bnew Function\b`),
		regexp.MustCompile(`\bXMLHttpRequest\b`), regexp.MustCompile(`\bWebSocket\b`), regexp.MustCompile(`\bimport\s*\(`),
		regexp.MustCompile(`\brequire\s*\(`), regexp.MustCompile(`<script`), regexp.MustCompile(`\bdocument\b`), regexp.MustCompile(`\bwindow\b`),
		regexp.MustCompile(`\bstyle=`), regexp.MustCompile(`\bhref=`), regexp.MustCompile(`\bsrc=`), regexp.MustCompile(`\bref=`),
	}
	importLine = regexp.MustCompile(`(?m)^\s*(?:import|export)\b.*$`)
)

func checkSolidForbidden(t testing.TB, label, jsx, css string) {
	t.Helper()
	for _, re := range forbiddenSolid {
		if loc := re.FindStringIndex(jsx); loc != nil {
			t.Errorf("%s: JSX contains forbidden %s: %q", label, re, jsx[loc[0]:loc[1]])
		}
	}
	for _, line := range importLine.FindAllString(jsx, -1) {
		line = strings.TrimSpace(line)
		if line != `import { For } from "solid-js";` && !strings.HasPrefix(line, "export default function ") {
			t.Errorf("%s: unexpected import or export %q", label, line)
		}
	}
	if strings.Count(jsx, "export default") != 1 {
		t.Errorf("%s: want exactly one default export", label)
	}
	for _, bad := range []string{"url(", "@import", "<", "expression("} {
		if strings.Contains(css, bad) {
			t.Errorf("%s: CSS contains %q", label, bad)
		}
	}
}

