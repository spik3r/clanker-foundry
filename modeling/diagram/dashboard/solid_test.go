func TestHTMLExamplesKeepDigestAndOutput(t *testing.T) {
	for name, want := range pinnedDigests {
		raw := example(t, name)
		g := generate(t, raw)
		if got := contract.HexSum(g.Canonical); got != want {
			t.Errorf("%s: canonical digest %s, want %s", name, got, want)
		}
		if bytes.Contains(g.Canonical, []byte("target")) {
			t.Errorf("%s: canonical encoding names target", name)
		}
		if _, ok := g.Files[FileHTML]; !ok || len(g.Files) != 2 {
			t.Errorf("%s: files %v", name, keys(g.Files))
		}
		// An explicit "html" is the same model.
		explicit := strings.Replace(raw, `"profileVersion": "dashboard/v1",`, `"profileVersion": "dashboard/v1", "target": "html",`, 1)
		if explicit == raw {
			t.Fatalf("%s: fixture has no profileVersion line", name)
		}
		e := generate(t, explicit)
		if !bytes.Equal(e.Canonical, g.Canonical) {
			t.Errorf("%s: explicit html changes the canonical model", name)
		}
		for f, b := range g.Files {
			if !bytes.Equal(e.Files[f], b) {
				t.Errorf("%s: explicit html changes %s", name, f)
			}
		}
	}
}

func keys(m map[string][]byte) []string {
	var k []string
	for n := range m {
		k = append(k, n)
	}
	return k
}

func TestTargetValues(t *testing.T) {
	for _, bad := range []string{`""`, `"Solid"`, `"react"`, `"HTML"`, `null`, `1`, `true`, `["solid"]`} {
		raw := strings.Replace(good, `"id": "WeeklyOps",`, `"id": "WeeklyOps", "target": `+bad+`,`, 1)
		if _, err := Decode([]byte(raw)); err == nil {
			t.Errorf("target %s was accepted", bad)
		}
	}
	m, err := Decode([]byte(solidOf(t, good)))
	if err != nil {
		t.Fatal(err)
	}
	c, _ := m.Canonical()
	if !strings.Contains(string(c), `"subtitle":"Week 45","target":"solid","datasets"`) {
		t.Errorf("canonical encoding does not place target after subtitle: %s", c)
	}
	// A programmatic model with target html normalizes to none.
	m.Target = TargetHTML
	if c2, _ := m.Canonical(); bytes.Contains(c2, []byte("target")) {
		t.Errorf("html target kept in canonical encoding: %s", c2)
	}
	// The solid target changes the digest.
	if digest(t, good) == digest(t, solidOf(t, good)) {
		t.Errorf("target does not change the digest")
	}
}

