func TestSolidCSSContract(t *testing.T) {
	css := solidCSS
	for _, v := range []string{"--text", "--muted", "--faint", "--border", "--panel", "--accent", "--warn", "--space-xs", "--space-sm", "--space-md", "--space-lg", "--font-xs", "--font-sm", "--radius-md"} {
		if !strings.Contains(css, "var("+v+",") {
			t.Errorf("css never reads %s", v)
		}
	}
	// Every host property is read with a fallback and none is defined here.
	for _, m := range regexp.MustCompile(`var\(--[a-z0-9-]+\)`).FindAllString(css, -1) {
		t.Errorf("custom property read without fallback: %s", m)
	}
	if regexp.MustCompile(`(^|[;{])\s*--[a-z]`).MatchString(css) {
		t.Errorf("css defines a custom property")
	}
	// Every selector starts with the class prefix; nothing styles bare elements.
	for _, line := range strings.Split(strings.TrimSpace(css), "\n") {
		if strings.HasPrefix(line, "@media") {
			continue
		}
		sel := line[:strings.Index(line, "{")]
		for _, s := range strings.Split(sel, ",") {
			s = strings.TrimSpace(s)
			if !regexp.MustCompile(`^(path)?\.fd-`).MatchString(s) {
				t.Errorf("selector %q is not prefixed", s)
			}
		}
	}
	// Every class the JSX uses is prefixed.
	out := renderSolid(t, solidOf(t, example(t, "sales-dashboard.json")))
	for _, m := range regexp.MustCompile(`class="([^"]*)"`).FindAllStringSubmatch(out, -1) {
		for _, c := range strings.Fields(m[1]) {
			if !strings.HasPrefix(c, ClassPrefix) {
				t.Errorf("class %q lacks the prefix", c)
			}
		}
	}
}

// hostileSolid builds two models of the same shape whose text differs: one
// plain, one made of attack strings for JSX and JavaScript.
func hostileSolid(t testing.TB, evil bool) string {
	t.Helper()
	pick := func(plain, bad string) string {
		if evil {
			return bad
		}
		return plain
	}
	attack := func(tag string) string {
		return tag + `</script>{}{{x}}` + "`${alert(1)}`" + `<script>"'\` + `\"</>&amp;{/*` + tag
	}
	r := strings.NewReplacer(
		`"Weekly operations"`, jsonStr(pick("Title", attack("T1"))),
		`"Week 45"`, jsonStr(pick("Sub", attack("S1"))),
		`"Orders placed"`, jsonStr(pick("Label", attack("L1"))),
		`"872"`, jsonStr(pick("Value", attack("V1"))),
		`"+4%"`, jsonStr(pick("Note", attack("N1"))),
		`"Orders by day"`, jsonStr(pick("Bars", attack("B1"))),
		`"Shipped per day"`, jsonStr(pick("Line", attack("B2"))),
		`"label": "Placed"`, `"label": `+jsonStr(pick("Placed", attack("C1"))),
		`"Mon"`, jsonStr(pick("Mon", attack("M1"))),
		`"Tue"`, jsonStr(pick("Tue", attack("M2"))),
		`"Daily detail"`, jsonStr(pick("Detail", attack("D1"))),
	)
	return solidOf(t, r.Replace(good))
}

func jsonStr(s string) string {
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	_ = enc.Encode(s)
	return strings.TrimSpace(buf.String())
}

func TestSolidHostileStringsAreInert(t *testing.T) {
	plain := renderSolid(t, hostileSolid(t, false))
	evil := renderSolid(t, hostileSolid(t, true))
	// With string literals emptied, a model whose text is hostile gives the
	// same source as one whose text is plain: no model text is outside a
	// literal, so none can be read as JSX or JavaScript.
	// The header line names the model digest, which differs; it holds no text.
	dropHeader := func(s string) string { return s[strings.IndexByte(s, '\n'):] }
	if a, b := outsideLiterals(dropHeader(plain)), outsideLiterals(dropHeader(evil)); a != b {
		pa, pb := strings.Split(a, "\n"), strings.Split(b, "\n")
		for i := range pa {
			if i >= len(pb) || pa[i] != pb[i] {
				t.Fatalf("code outside string literals depends on model text at line %d\nplain: %s\nevil:  %s", i+1, pa[i], pb[min(i, len(pb)-1)])
			}
		}
		t.Fatalf("code outside string literals depends on model text: %d lines against %d", len(pa), len(pb))
	}
	for _, tag := range []string{"T1", "S1", "L1", "V1", "N1", "B1", "B2", "C1", "M1", "M2", "D1"} {
		if !strings.Contains(evil, tag) {
			t.Errorf("hostile text %s is missing from the output", tag)
		}
		if strings.Contains(outsideLiterals(evil), tag) {
			t.Errorf("hostile text %s is outside a string literal", tag)
		}
	}
	// No raw markup character from model text inside any literal, either.
	for _, lit := range literalRE.FindAllString(evil, -1) {
		if strings.ContainsAny(lit, "<>&") {
			t.Errorf("literal holds a raw markup character: %s", lit)
		}
	}
	// Outside literals only generator text remains: braces balance and every
	// '<' opens a known tag.
	rest := outsideLiterals(evil)
	if strings.Count(rest, "{") != strings.Count(rest, "}") || strings.Count(rest, "(") != strings.Count(rest, ")") {
		t.Errorf("unbalanced braces or parentheses outside literals")
	}
	known := regexp.MustCompile(`</?(div|header|h1|h2|p|main|section|article|ul|li|svg|rect|line|text|path|circle|title|table|thead|tbody|tr|th|td|For)\b`)
	for _, m := range regexp.MustCompile(`<[^ ]*`).FindAllString(rest, -1) {
		if !known.MatchString(m) {
			t.Errorf("unknown tag start %q", m)
		}
	}
	checkSolidForbidden(t, "hostile", evil, solidCSS)
	// The literals decode to the original text: unescaping loses nothing.
	for _, lit := range literalRE.FindAllString(evil, -1) {
		var s string
		if err := json.Unmarshal([]byte(lit), &s); err != nil {
			t.Errorf("literal %s is not a valid string: %v", lit, err)
		}
	}
	var title string
	for _, lit := range literalRE.FindAllString(evil, -1) {
		if strings.Contains(lit, "T1") {
			if err := json.Unmarshal([]byte(lit), &title); err != nil {
				t.Fatal(err)
			}
			break
		}
	}
	if want := "T1</script>{}{{x}}`${alert(1)}`<script>\"'\\\\\"</>&amp;{/*T1"; title != want {
		t.Errorf("title literal decodes to %q, want %q", title, want)
	}
}

func TestJSStringEscapes(t *testing.T) {
	bs, ls := `\`, string(rune(0x2028))
	cases := map[string]string{
		"a\"b":         `"a\"b"`,
		`a\b`:          `"a\\b"`,
		"a\nb\tc\rd":   `"a\nb\tc\rd"`,
		"<>&":          `"` + bs + `u003c` + bs + `u003e` + bs + `u0026"`,
		"a" + ls + "b": `"a` + bs + `u2028b"`,
		"\x00\x1f\x7f": `"\u0000\u001f\u007f"`,
		"é€😀":          `"é€😀"`,
		"`${x}`":       "\"`${x}`\"",
	}
	for in, want := range cases {
		if got := jsString(in); got != want {
			t.Errorf("jsString(%q) = %s, want %s", in, got, want)
		}
		var back string
		if err := json.Unmarshal([]byte(jsString(in)), &back); err != nil || back != in {
			t.Errorf("jsString(%q) does not round-trip: %q, %v", in, back, err)
		}
	}
}

var (
	htmlID  = regexp.MustCompile(`<article data-id="([^"]*)" data-kind="([^"]*)">`)
	jsxID   = regexp.MustCompile(`<article class="fd-widget" data-id=\{"([^"]*)"\} data-kind=\{"([^"]*)"\}>`)
	htmlGeo = regexp.MustCompile(`\s(x|y|x1|y1|x2|y2|cx|cy|width|height|d|data-v)="([^"]*)"`)
	jsxGeo  = regexp.MustCompile(`\s(x|y|x1|y1|x2|y2|cx|cy|width|height|d|data-v)=\{"([^"]*)"\}`)
)

func TestSolidMatchesHTMLStructure(t *testing.T) {
	for _, name := range exampleModels {
		raw := example(t, name)
		h := render(t, raw)
		s := renderSolid(t, solidOf(t, raw))
		hid, sid := htmlID.FindAllStringSubmatch(h, -1), jsxID.FindAllStringSubmatch(s, -1)
		if len(hid) == 0 || len(hid) != len(sid) {
			t.Fatalf("%s: %d html widgets, %d solid widgets", name, len(hid), len(sid))
		}
		for i := range hid {
			if hid[i][1] != sid[i][1] || hid[i][2] != sid[i][2] {
				t.Errorf("%s: widget %d is %v in html, %v in solid", name, i, hid[i][1:], sid[i][1:])
			}
		}
		for _, tag := range []string{"<section", "<h2", "<svg", "<circle", "<rect", "<line", "<path", "<title>", "<th ", "<ul"} {
			a, b := strings.Count(h, tag), strings.Count(s, tag)
			if tag == "<title>" {
				a-- // the html page has a document title; the component has none
			}
			if a != b {
				t.Errorf("%s: %d %q in html, %d in solid", name, a, tag, b)
			}
		}
		// The same geometry, in the same order: coordinates, path data, tick values.
		hg, sg := htmlGeo.FindAllStringSubmatch(h, -1), jsxGeo.FindAllStringSubmatch(s, -1)
		if len(hg) != len(sg) {
			t.Fatalf("%s: %d geometry attributes in html, %d in solid", name, len(hg), len(sg))
		}
		for i := range hg {
			if hg[i][1] != sg[i][1] || hg[i][2] != sg[i][2] {
				t.Fatalf("%s: geometry %d is %v in html, %v in solid", name, i, hg[i][1:], sg[i][1:])
			}
		}
	}
}

