// ClassPrefix starts every class name the solid target emits.
const ClassPrefix = "fd-"

// jsReserved lists ids that cannot name the exported component: JavaScript
// reserved words (module code is strict), names that are not bindable, and the
// names the emitted module itself uses.
var jsReserved = func() map[string]bool {
	m := map[string]bool{}
	for _, w := range strings.Fields(`
		break case catch class const continue debugger default delete do else enum export
		extends false finally for function if import in instanceof new null return super
		switch this throw true try typeof var void while with yield let static implements
		interface package private protected public await arguments eval undefined NaN Infinity
		For Show DATASETS Object props`) {
		m[w] = true
	}
	return m
}()

// jsString writes s as a double-quoted JavaScript string literal; see
// jsxemit.String.
func jsString(s string) string { return jsxemit.String(s) }

// prefixed turns HTML class names into the prefixed names of the solid target.
func prefixed(class string) string {
	parts := strings.Fields(class)
	for i, p := range parts {
		parts[i] = ClassPrefix + p
	}
	return strings.Join(parts, " ")
}

// jsx is the shared indenting writer. Every attribute value that is not a
// fixed class name is written as {"..."}, a JavaScript string literal, and every
// text child as {"..."}; model text never appears as raw JSX.
type jsx = jsxemit.Writer

func attr(name, value string) string { return jsxemit.Attr(name, value) }

func classAttr(class string) string { return ` class="` + prefixed(class) + `"` }

// RenderSolid writes Dashboard.jsx for a validated, normalized model. digest is
// the canonical model digest named in the header line.
func RenderSolid(m Model, g contract.Generator, digest string) []byte {
	j := &jsx{}
	hasTable := false
	byID := map[string]Widget{}
	for _, x := range m.Widgets {
		byID[x.ID] = x
		hasTable = hasTable || x.Kind == KindTable
	}
	j.Line("// Code generated by " + g.ID + " " + g.Version + " from model " + digest + ". DO NOT EDIT.")
	j.Line("")
	if hasTable {
		j.Line(`import { For } from "solid-js";`)
		j.Line("")
	}
	writeData(j, m)
	j.Line("")
	j.Line("export default function " + m.ID + "(props) {")
	j.Depth++
	j.Line("return (")
	j.Depth++
	j.Line(`<div class={"` + ClassPrefix + `dashboard" + (props.class ? " " + props.class : "")}>`)
	j.Depth++
	j.Line("<header" + classAttr("header") + ">")
	j.Depth++
	j.Line("<h1" + classAttr("title") + ">{" + jsString(m.Title) + "}</h1>")
	if m.Subtitle != "" {
		j.Line("<p" + classAttr("subtitle") + ">{" + jsString(m.Subtitle) + "}</p>")
	}
	j.Depth--
	j.Line("</header>")
	j.Line("<main" + classAttr("main") + ">")
	j.Depth++
	for _, row := range m.Layout {
		j.Line("<section" + classAttr("row cols-"+strconv.Itoa(len(row))) + ">")
		j.Depth++
		for _, id := range row {
			writeWidgetJSX(j, m, byID[id])
		}
		j.Depth--
		j.Line("</section>")
	}
	j.Depth--
	j.Line("</main>")
	j.Depth--
	j.Line("</div>")
	j.Depth--
	j.Line(");")
	j.Depth--
	j.Line("}")
	return []byte(j.String())
}

// writeData writes the datasets as one frozen array of frozen records. Cells
// are strings: text as given, numbers as canonical decimal text.
func writeData(j *jsx, m Model) {
	if len(m.Datasets) == 0 {
		j.Line("const DATASETS = Object.freeze([]);")
		return
	}
	j.Line("const DATASETS = Object.freeze([")
	j.Depth++
	for _, ds := range m.Datasets {
		j.Line("Object.freeze({")
		j.Depth++
		j.Line("id: " + jsString(ds.ID) + ",")
		j.Line("columns: Object.freeze([")
		j.Depth++
		for _, c := range ds.Columns {
			j.Line("Object.freeze({ id: " + jsString(c.ID) + ", label: " + jsString(c.Label) + ", type: " + jsString(c.Type) + " }),")
		}
		j.Depth--
		j.Line("]),")
		if len(ds.Rows) == 0 {
			j.Line("rows: Object.freeze([]),")
		} else {
			j.Line("rows: Object.freeze([")
			j.Depth++
			for _, row := range ds.Rows {
				cells := make([]string, len(row))
				for i, c := range row {
					cells[i] = jsString(c.String())
				}
				j.Line("Object.freeze([" + strings.Join(cells, ", ") + "]),")
			}
			j.Depth--
			j.Line("]),")
		}
		j.Depth--
		j.Line("}),")
	}
	j.Depth--
	j.Line("]);")
}

func writeWidgetJSX(j *jsx, m Model, x Widget) {
	j.Line("<article" + classAttr("widget") + attr("data-id", x.ID) + attr("data-kind", x.Kind) + ">")
	j.Depth++
	switch x.Kind {
	case KindStat:
		j.Line("<p" + classAttr("stat-label") + ">{" + jsString(x.Label) + "}</p>")
		j.Line("<p" + classAttr("stat-value") + ">{" + jsString(x.Value) + "}</p>")
		if x.Note != "" {
			j.Line("<p" + classAttr("note") + ">{" + jsString(x.Note) + "}</p>")
		}
	case KindTable:
		j.Line("<h2" + classAttr("heading") + ">{" + jsString(x.Title) + "}</h2>")
		writeTableJSX(j, m, x)
	default:
		j.Line("<h2" + classAttr("heading") + ">{" + jsString(x.Title) + "}</h2>")
		writeChartJSX(j, m.dataset(x.Dataset), x)
	}
	j.Depth--
	j.Line("</article>")
}

func writeTableJSX(j *jsx, m Model, x Widget) {
	ds := m.dataset(x.Dataset)
	di := 0
	for i, d := range m.Datasets {
		if d.ID == ds.ID {
			di = i
		}
	}
	idx := make([]int, len(x.Columns))
	for i, id := range x.Columns {
		idx[i] = ds.column(id)
	}
	numCls := func(c Column) string {
		if c.Type == TypeNumber {
			return classAttr("num")
		}
		return ""
	}
	j.Line("<div" + classAttr("scroll") + ` role="region" tabindex="0"` + attr("aria-label", x.Title) + ">")
	j.Depth++
	j.Line("<table" + classAttr("table") + ">")
	j.Depth++
	j.Line("<thead>")
	j.Depth++
	j.Line("<tr>")
	j.Depth++
	for _, c := range idx {
		col := ds.Columns[c]
		j.Line(`<th scope="col"` + numCls(col) + ">{" + jsString(col.Label) + "}</th>")
	}
	j.Depth--
	j.Line("</tr>")
	j.Depth--
	j.Line("</thead>")
	j.Line("<tbody>")
	j.Depth++
	j.Line("<For each={DATASETS[" + strconv.Itoa(di) + "].rows}>")
	j.Depth++
	j.Line("{(row) => (")
	j.Depth++
	j.Line("<tr>")
	j.Depth++
	for _, c := range idx {
		j.Line("<td" + numCls(ds.Columns[c]) + ">{row[" + strconv.Itoa(c) + "]}</td>")
	}
	j.Depth--
	j.Line("</tr>")
	j.Depth--
	j.Line(")}")
	j.Depth--
	j.Line("</For>")
	j.Depth--
	j.Line("</tbody>")
	j.Depth--
	j.Line("</table>")
	j.Depth--
	j.Line("</div>")
}

// writeChartJSX writes the legend and svg of a chart from the same geometry
// the HTML target uses.
func writeChartJSX(j *jsx, ds Dataset, x Widget) {
	g := layoutChart(ds, x)
	if len(g.legend) > 0 {
		j.Line("<ul" + classAttr("legend") + ">")
		j.Depth++
		for _, it := range g.legend {
			j.Line("<li>")
			j.Depth++
			j.Line("<svg" + classAttr("sw") + attr("viewBox", "0 0 24 12") + attr("width", "24") + attr("height", "12") + attr("aria-hidden", "true") + ">")
			j.Depth++
			if it.line {
				j.Line("<path" + classAttr("l"+it.pos) + attr("d", "M0 6H24") + " />")
			} else {
				j.Line("<rect" + classAttr("b"+it.pos) + attr("x", "0") + attr("y", "0") + attr("width", "24") + attr("height", "12") + " />")
			}
			j.Depth--
			j.Line("</svg>")
			j.Line("{" + jsString(it.label) + "}")
			j.Depth--
			j.Line("</li>")
		}
		j.Depth--
		j.Line("</ul>")
	}
	j.Line("<svg" + classAttr("chart") + attr("viewBox", "0 0 "+strconv.Itoa(chartW)+" "+strconv.Itoa(chartH)) + ` role="img"` + attr("aria-label", g.ariaLabel) + ">")
	j.Depth++
	for _, e := range g.els {
		open := "<" + e.tag + classAttr(e.class)
		for _, a := range e.attrs {
			open += attr(a[0], a[1])
		}
		switch {
		case e.isText:
			j.Line(open + ">{" + jsString(e.text) + "}</text>")
		case e.hasTitle:
			j.Line(open + ">")
			j.Depth++
			j.Line("<title>{" + jsString(e.title) + "}</title>")
			j.Depth--
			j.Line("</" + e.tag + ">")
		default:
			j.Line(open + " />")
		}
	}
	j.Depth--
	j.Line("</svg>")
}
