package sequence

import (
	"fmt"
	"strings"

	"github.com/spik3r/clanker-foundry/modeling/diagram/contract"
	"github.com/spik3r/clanker-foundry/modeling/diagram/internal/svgx"
)

const svgStyle = `.bg{fill:#fff}
.title{font-size:16px;font-weight:bold;fill:#222}
.head{fill:#eef1f5;stroke:#222;stroke-width:1.5}
.head-label{fill:#222}
.figure{fill:#fff;stroke:#222;stroke-width:1.5;stroke-linecap:round}
.lifeline{stroke:#8a8f98;stroke-width:1;stroke-dasharray:5 4}
.msg{fill:none;stroke:#222;stroke-width:1.5}
.msg-reply{stroke-dasharray:6 4}
.msg-label{font-size:11px;fill:#222}
.head-filled{fill:#222;stroke:#222;stroke-width:1}
.head-open{fill:none;stroke:#222;stroke-width:1.5}
.note{fill:#fff7d6;stroke:#8a7a2e;stroke-width:1}
.note-label{font-size:11px;fill:#222}
.frame{fill:none;stroke:#555;stroke-width:1.2}
.frame-tab{fill:#eef1f5;stroke:#555;stroke-width:1.2}
.frame-kind{font-size:11px;font-weight:bold;fill:#222}
.frame-label{font-size:11px;fill:#222}`

func box(r Rect) string { return fmt.Sprintf("%d %d %d %d", r.X, r.Y, r.W, r.H) }

// SVG renders the layout as an inert picture: no script, no event attributes,
// no external references and no embedded fonts or images. Every drawn element
// group carries data-id and data-kind.
func SVG(m Model, l Layout, g contract.Generator) []byte {
	var b strings.Builder
	w, h := l.Width, l.Height
	b.WriteString(`<?xml version="1.0" encoding="UTF-8"?>` + "\n")
	fmt.Fprintf(&b, `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 %d %d" width="%d" height="%d" font-family="Helvetica, Arial, sans-serif" font-size="12" role="img">`+"\n", w, h, w, h)
	fmt.Fprintf(&b, "<title>%s</title>\n", svgx.Esc(m.Title))
	fmt.Fprintf(&b, "<desc>%s diagram %s, generated by %s %s</desc>\n", Profile, svgx.Esc(m.ID), g.ID, g.Version)
	b.WriteString(`<defs>` +
		`<marker id="head-filled" viewBox="0 0 10 10" refX="10" refY="5" markerWidth="9" markerHeight="9" markerUnits="userSpaceOnUse" orient="auto"><path class="head-filled" d="M0 0 L10 5 L0 10 z"/></marker>` +
		`<marker id="head-open" viewBox="0 0 10 10" refX="10" refY="5" markerWidth="9" markerHeight="9" markerUnits="userSpaceOnUse" orient="auto"><path class="head-open" d="M0 0 L10 5 L0 10"/></marker>` +
		"</defs>\n")
	b.WriteString("<style>\n" + svgStyle + "\n</style>\n")
	fmt.Fprintf(&b, `<rect class="bg" x="0" y="0" width="%d" height="%d"/>`+"\n", w, h)
	title := svgx.Truncate(m.Title, max(8, (w-2*margin)/titleCharPx))
	fmt.Fprintf(&b, `<text class="title" data-id="title" data-kind="title" x="%d" y="%d">%s</text>`+"\n", l.Title.X, l.Title.Y, svgx.Esc(title))

	for _, f := range l.Frames {
		fmt.Fprintf(&b, `<g class="frame-group" data-id="%s" data-kind="%s" data-first="%s" data-last="%s" data-box="%s">`,
			svgx.Esc(f.G.ID), f.G.Kind, svgx.Esc(f.G.First), svgx.Esc(f.G.Last), box(f.Box))
		fmt.Fprintf(&b, `<rect class="frame" x="%d" y="%d" width="%d" height="%d"/>`, f.Box.X, f.Box.Y, f.Box.W, f.Box.H)
		fmt.Fprintf(&b, `<rect class="frame-tab" x="%d" y="%d" width="%d" height="%d"/>`, f.Tab.X, f.Tab.Y, f.Tab.W, f.Tab.H)
		fmt.Fprintf(&b, `<text class="frame-kind" x="%d" y="%d">%s</text>`, f.Tab.X+8, f.Tab.Y+12, f.G.Kind)
		fmt.Fprintf(&b, `<text class="frame-label" x="%d" y="%d">[%s]</text>`, f.Tab.X+f.Tab.W+6, f.Tab.Y+12, svgx.Esc(f.Label))
		b.WriteString("</g>\n")
	}

	for _, p := range l.Participants {
		fmt.Fprintf(&b, `<line class="lifeline" data-id="%s" data-kind="lifeline" x1="%d" y1="%d" x2="%d" y2="%d"/>`+"\n",
			svgx.Esc(p.P.ID), p.CX, l.LifelineY1, p.CX, l.LifelineY2)
	}

	for _, s := range l.Steps {
		switch s.S.Kind {
		case StepNote:
			fmt.Fprintf(&b, `<g class="note-group" data-id="%s" data-kind="note" data-over="%s" data-box="%s">`,
				svgx.Esc(s.S.ID), svgx.Esc(strings.Join(s.S.Over, " ")), box(s.Box))
			fmt.Fprintf(&b, `<rect class="note" x="%d" y="%d" width="%d" height="%d"/>`, s.Box.X, s.Box.Y, s.Box.W, s.Box.H)
			fmt.Fprintf(&b, `<text class="note-label" text-anchor="middle">`)
			for i, ln := range s.Lines {
				fmt.Fprintf(&b, `<tspan x="%d" y="%d">%s</tspan>`, s.Box.X+s.Box.W/2, s.Box.Y+16+i*lineH, svgx.Esc(ln))
			}
			b.WriteString("</text></g>\n")
		default:
			marker, class := "head-open", "msg"
			if s.S.Style == StyleSync {
				marker = "head-filled"
			}
			if s.S.Style == StyleReply {
				class = "msg msg-reply"
			}
			fmt.Fprintf(&b, `<g class="message-group" data-id="%s" data-kind="message" data-style="%s" data-from="%s" data-to="%s" data-box="%s">`,
				svgx.Esc(s.S.ID), s.S.Style, svgx.Esc(s.S.From), svgx.Esc(s.S.To), box(s.Box))
			if s.S.From == s.S.To {
				fmt.Fprintf(&b, `<path class="%s" d="M%d %d L%d %d L%d %d L%d %d" marker-end="url(#%s)"/>`,
					class, s.X1, s.Y, s.X1+loopW, s.Y, s.X1+loopW, s.Y+16, s.X1, s.Y+16, marker)
				fmt.Fprintf(&b, `<text class="msg-label" x="%d" y="%d">%s</text>`, s.LabelX, s.Y+12, svgx.Esc(s.Lines[0]))
			} else {
				fmt.Fprintf(&b, `<path class="%s" d="M%d %d L%d %d" marker-end="url(#%s)"/>`, class, s.X1, s.Y, s.X2, s.Y, marker)
				fmt.Fprintf(&b, `<text class="msg-label" text-anchor="middle" x="%d" y="%d">%s</text>`, s.LabelX, s.Y-6, svgx.Esc(s.Lines[0]))
			}
			b.WriteString("</g>\n")
		}
	}

	for _, p := range l.Participants {
		bx := p.Box
		fmt.Fprintf(&b, `<g class="participant-group" data-id="%s" data-kind="%s" data-box="%s">`, svgx.Esc(p.P.ID), p.P.Kind, box(bx))
		if p.P.Kind == KindActor {
			top := bx.Y
			fmt.Fprintf(&b, `<circle class="figure" cx="%d" cy="%d" r="7"/>`, p.CX, top+8)
			fmt.Fprintf(&b, `<path class="figure" d="M%d %d L%d %d M%d %d L%d %d M%d %d L%d %d M%d %d L%d %d"/>`,
				p.CX, top+15, p.CX, top+26,
				p.CX-10, top+19, p.CX+10, top+19,
				p.CX, top+26, p.CX-8, top+36,
				p.CX, top+26, p.CX+8, top+36)
			lines := svgx.Wrap(p.P.Label, headBudget, 2)
			fmt.Fprintf(&b, `<text class="head-label" text-anchor="middle">`)
			for i, ln := range lines {
				fmt.Fprintf(&b, `<tspan x="%d" y="%d">%s</tspan>`, p.CX, top+48+i*lineH, svgx.Esc(ln))
			}
			b.WriteString("</text>")
		} else {
			fmt.Fprintf(&b, `<rect class="head" x="%d" y="%d" width="%d" height="%d"/>`, bx.X, bx.Y, bx.W, bx.H)
			lines := svgx.Wrap(p.P.Label, headBudget, 3)
			first := bx.Y + bx.H/2 - (len(lines)-1)*lineH/2 + 4
			fmt.Fprintf(&b, `<text class="head-label" text-anchor="middle">`)
			for i, ln := range lines {
				fmt.Fprintf(&b, `<tspan x="%d" y="%d">%s</tspan>`, p.CX, first+i*lineH, svgx.Esc(ln))
			}
			b.WriteString("</text>")
		}
		b.WriteString("</g>\n")
	}
	b.WriteString("</svg>\n")
	return []byte(b.String())
}
