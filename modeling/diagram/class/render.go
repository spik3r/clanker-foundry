const titleCharPx = 9

const svgStyle = `.bg{fill:#fff}
.title{font-size:16px;font-weight:bold;fill:#222}
.class{fill:#fff;stroke:#222;stroke-width:1.5}
.sep{stroke:#222;stroke-width:1}
.stereo{font-size:11px;fill:#444}
.name{font-weight:bold;fill:#222}
.member{font-size:11px;fill:#222}
.rel{fill:none;stroke:#333;stroke-width:1.5}
.dashed{stroke-dasharray:6 4}
.hollow{fill:#fff;stroke:#333;stroke-width:1.5}
.solid{fill:#333;stroke:#333;stroke-width:1.5}
.open{fill:none;stroke:#333;stroke-width:1.5}
.rel-label{font-size:11px;fill:#222}`

func box(r Rect) string { return fmt.Sprintf("%d %d %d %d", r.X, r.Y, r.W, r.H) }

// decoration returns the path of the end shape at tip, where dir is +1 when
// the line leaves the tip downwards and -1 when it leaves it upwards.
func decoration(kind string, tip Point, dir int) (class, shape, d string) {
	x, y := tip.X, tip.Y
	switch kind {
	case "triangle":
		return "hollow", kind, fmt.Sprintf("M%d %d L%d %d L%d %d z", x, y, x+6, y+14*dir, x-6, y+14*dir)
	case "diamond-hollow", "diamond-filled":
		c := "hollow"
		if kind == "diamond-filled" {
			c = "solid"
		}
		return c, "diamond", fmt.Sprintf("M%d %d L%d %d L%d %d L%d %d z", x, y, x+6, y+8*dir, x, y+16*dir, x-6, y+8*dir)
	default: // open arrow
		return "open", "arrow", fmt.Sprintf("M%d %d L%d %d L%d %d", x+6, y+10*dir, x, y, x-6, y+10*dir)
	}
}

// ends names the shape drawn at each end of a relation kind: "" for none.
func ends(kind string) (atFrom, atTo string) {
	switch kind {
	case Inheritance, Realization:
		return "", "triangle"
	case Directed, Dependency:
		return "", "arrow"
	case Aggregation:
		return "diamond-hollow", ""
	case Composition:
		return "diamond-filled", ""
	}
	return "", ""
}

// SVG renders the layout as an inert picture: no script, no event attributes,
// no external references and no embedded fonts or images. Every drawn element
// group carries data-id and data-kind.
func SVG(m Model, l Layout, g contract.Generator) []byte {
	var b strings.Builder
	w, h := l.Width, l.Height
	b.WriteString(`<?xml version="1.0" encoding="UTF-8"?>` + "\n")
	fmt.Fprintf(&b, `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 %d %d" width="%d" height="%d" font-family="Helvetica, Arial, sans-serif" font-size="12" role="img">`+"\n", w, h, w, h)
	fmt.Fprintf(&b, "<title>%s</title>\n", svgx.Esc(m.Title))
	fmt.Fprintf(&b, "<desc>%s diagram %s, generated by %s %s</desc>\n", Profile, svgx.Esc(m.ID), g.ID, g.Version)
	b.WriteString("<style>\n" + svgStyle + "\n</style>\n")
	fmt.Fprintf(&b, `<rect class="bg" x="0" y="0" width="%d" height="%d"/>`+"\n", w, h)
	title := svgx.Truncate(m.Title, max(8, (w-2*margin)/titleCharPx))
	fmt.Fprintf(&b, `<text class="title" data-id="title" data-kind="title" x="%d" y="30">%s</text>`+"\n", margin, svgx.Esc(title))

	// Relations first, so class boxes sit on top of any line end.
	for _, r := range l.Relations {
		var pts strings.Builder
		var d strings.Builder
		for i, p := range r.Points {
			if i == 0 {
				d.WriteString("M")
			} else {
				d.WriteString(" L")
				pts.WriteString(" ")
			}
			fmt.Fprintf(&d, "%d %d", p.X, p.Y)
			fmt.Fprintf(&pts, "%d,%d", p.X, p.Y)
		}
		cls := "rel"
		if r.R.Kind == Realization || r.R.Kind == Dependency {
			cls += " dashed"
		}
		fmt.Fprintf(&b, `<g class="relation-group" data-id="%s" data-kind="%s" data-from="%s" data-to="%s" data-points="%s">`,
			svgx.Esc(r.R.ID), r.R.Kind, svgx.Esc(r.R.From), svgx.Esc(r.R.To), pts.String())
		fmt.Fprintf(&b, `<path class="%s" d="%s"/>`, cls, d.String())
		atFrom, atTo := ends(r.R.Kind)
		first, last := r.Points[0], r.Points[len(r.Points)-1]
		dirOf := func(p, q Point) int { // direction of the first segment leaving p towards q
			if q.Y >= p.Y {
				return 1
			}
			return -1
		}
		if atFrom != "" {
			c, shape, dd := decoration(atFrom, first, dirOf(first, r.Points[1]))
			fmt.Fprintf(&b, `<path class="%s" data-end="from" data-shape="%s" d="%s"/>`, c, shape, dd)
		}
		if atTo != "" {
			c, shape, dd := decoration(atTo, last, dirOf(last, r.Points[len(r.Points)-2]))
			fmt.Fprintf(&b, `<path class="%s" data-end="to" data-shape="%s" d="%s"/>`, c, shape, dd)
		}
		for _, t := range []struct {
			role string
			g    *TextGeom
		}{{"label", r.Label}, {"fromLabel", r.FromLabel}, {"toLabel", r.ToLabel}} {
			if t.g == nil {
				continue
			}
			fmt.Fprintf(&b, `<text class="rel-label" data-id="%s" data-kind="%s" data-box="%s" text-anchor="%s" x="%d" y="%d">%s</text>`,
				svgx.Esc(r.R.ID), t.role, box(t.g.Box), t.g.Anchor, t.g.X, t.g.Y, svgx.Esc(t.g.Text))
		}
		b.WriteString("</g>\n")
	}

	for _, c := range l.Classes {
		bx := c.Box
		fmt.Fprintf(&b, `<g class="class-group" data-id="%s" data-kind="%s" data-box="%s">`, svgx.Esc(c.C.ID), c.C.Kind, box(bx))
		fmt.Fprintf(&b, `<rect class="class" x="%d" y="%d" width="%d" height="%d"/>`, bx.X, bx.Y, bx.W, bx.H)
		fmt.Fprintf(&b, `<line class="sep" x1="%d" y1="%d" x2="%d" y2="%d"/>`, bx.X, bx.Y+c.NameH, bx.X+bx.W, bx.Y+c.NameH)
		fmt.Fprintf(&b, `<line class="sep" x1="%d" y1="%d" x2="%d" y2="%d"/>`, bx.X, bx.Y+c.NameH+c.AttrH, bx.X+bx.W, bx.Y+c.NameH+c.AttrH)
		y := bx.Y + 18
		cx := bx.X + bx.W/2
		if c.Stere != "" {
			fmt.Fprintf(&b, `<text class="stereo" text-anchor="middle" x="%d" y="%d">%s</text>`, cx, y, c.Stere)
			y += lineH
		}
		fmt.Fprintf(&b, `<text class="name" text-anchor="middle" x="%d" y="%d">%s</text>`, cx, y, svgx.Esc(c.Name))
		for i, s := range c.Attrs {
			fmt.Fprintf(&b, `<text class="member" data-kind="attribute" x="%d" y="%d">%s</text>`, bx.X+boxPadX, bx.Y+c.NameH+16+i*lineH, svgx.Esc(s))
		}
		for i, s := range c.Ops {
			fmt.Fprintf(&b, `<text class="member" data-kind="operation" x="%d" y="%d">%s</text>`, bx.X+boxPadX, bx.Y+c.NameH+c.AttrH+16+i*lineH, svgx.Esc(s))
		}
		b.WriteString("</g>\n")
	}
	b.WriteString("</svg>\n")
	return []byte(b.String())
}
