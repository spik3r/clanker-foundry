const exampleName = "evidence-atlas-page"

func example(t testing.TB) []byte {
	t.Helper()
	b, err := os.ReadFile(filepath.Join("..", "examples", exampleName+".json"))
	if err != nil {
		t.Fatal(err)
	}
	return b
}

func jsxOf(t testing.TB, raw string) string {
	t.Helper()
	return string(generated(t, raw).Files[FileJSX])
}

// literalRE matches one JavaScript double-quoted string literal.
var literalRE = regexp.MustCompile(`"(?:[^"\\\n]|\\.)*"`)

// outsideLiterals returns the source with every string literal emptied.
func outsideLiterals(src string) string { return literalRE.ReplaceAllString(src, `""`) }

func TestFilesAndHeader(t *testing.T) {
	g := generated(t, string(example(t)))
	if len(g.Files) != 3 || g.Files[FileJSX] == nil || g.Files[FileSlots] == nil || g.Files[FileModel] == nil {
		t.Fatalf("files %v", keys(g.Files))
	}
	want := "// Code generated by diagramgen 1.4.0 from model " + contract.HexSum(g.Canonical) + ". DO NOT EDIT.\n"
	if !strings.HasPrefix(string(g.Files[FileJSX]), want) {
		t.Errorf("header line is not %q", want)
	}
	if !strings.Contains(string(g.Files[FileJSX]), "\nexport default function EvidenceAtlasContent(props) {\n") {
		t.Errorf("no default export named from the id")
	}
	res, err := contract.Assemble(Profiler{}, testGen, example(t))
	if err != nil {
		t.Fatal(err)
	}
	if _, ok := res.Files[contract.ManifestName]; !ok || len(res.Files) != 4 {
		t.Errorf("assembled files %v", keys(res.Files))
	}
}

func keys(m map[string][]byte) []string {
	var k []string
	for n := range m {
		k = append(k, n)
	}
	return k
}

func TestExampleMatchesCommittedOutput(t *testing.T) {
	res, err := contract.Assemble(Profiler{}, testGen, example(t))
	if err != nil {
		t.Fatal(err)
	}
	drift, err := contract.Drift(res.Files, filepath.Join("..", "examples", "generated", exampleName))
	if err != nil {
		t.Fatal(err)
	}
	if len(drift) > 0 {
		t.Fatalf("committed output differs from regenerated output (run: go run ./cmd/diagramgen generate examples/%s.json <new dir>):\n%s", exampleName, strings.Join(drift, "\n"))
	}
}

func TestDeterministic(t *testing.T) {
	for _, raw := range []string{string(example(t)), good} {
		first := generated(t, raw)
		for i := 0; i < 5; i++ {
			again := generated(t, raw)
			if !bytes.Equal(first.Canonical, again.Canonical) {
				t.Fatalf("canonical encoding differs between runs")
			}
			for f, b := range first.Files {
				if !bytes.Equal(b, again.Files[f]) {
					t.Fatalf("%s differs between runs", f)
				}
			}
		}
	}
}

// attack builds text that would break out of a JSX child, a JSX attribute, a
// JavaScript string or a template literal, and carries a tag to find again.
func attack(tag string) string {
	return tag + `</script>{}{{x}}` + "`${alert(1)}`" + `<script>"'\` + `\"</>&amp;{/*` + tag
}

// hostile returns the good model with every text member replaced either by
// plain words or by attack text, so the two differ only in text.
func hostile(t testing.TB, evil bool) (string, []string) {
	t.Helper()
	var texts []string
	text := func(plain, tag string) string {
		if !evil {
			return plain
		}
		s := attack(tag)
		texts = append(texts, s)
		return s
	}
	raw := mut(t, func(m obj) {
		m["title"] = text("Title", "T1")
		m["purpose"] = text("Purpose", "P1")
		b := m["bottomLine"].(obj)
		b["finding"] = text("Finding", "F1")
		b["confidence"] = text("Confidence", "C1")
		b["limitation"] = text("Limitation", "L1")
		b["context"] = []any{text("Context", "X1"), text("Context two", "X2")}
		item(t, m, "explore", 1)["title"] = text("Head", "H1")
		item(t, m, "explore", 1)["description"] = text("Desc", "H2")
		item(t, m, "explore", 3)["paragraphs"] = []any{text("Para", "R1"), text("Para two", "R2")}
		item(t, m, "explore", 4)["title"] = text("Head two", "H3")
		mp := item(t, m, "method", 0)
		mp["title"] = text("Method", "M1")
		mp["description"] = text("Mdesc", "M2")
		mp["points"] = []any{text("Point", "M3"), text("Point two", "M4")}
		item(t, m, "sources", 0)["title"] = text("Sources", "S1")
		item(t, m, "sources", 0)["description"] = text("Sdesc", "S2")
	})
	return raw, texts
}

func TestHostileStringsAreInert(t *testing.T) {
	plainRaw, _ := hostile(t, false)
	evilRaw, texts := hostile(t, true)
	plain, evil := jsxOf(t, plainRaw), jsxOf(t, evilRaw)
	// The header line names the model digest, which differs; it holds no text.
	dropHeader := func(s string) string { return s[strings.IndexByte(s, '\n'):] }
	if a, b := outsideLiterals(dropHeader(plain)), outsideLiterals(dropHeader(evil)); a != b {
		pa, pb := strings.Split(a, "\n"), strings.Split(b, "\n")
		for i := range pa {
			if i >= len(pb) || pa[i] != pb[i] {
				t.Fatalf("code outside string literals depends on model text at line %d\nplain: %s\nevil:  %s", i+1, pa[i], pb[min(i, len(pb)-1)])
			}
		}
		t.Fatalf("code outside string literals depends on model text: %d lines against %d", len(pa), len(pb))
	}
	// Every attack text comes back from its literal exactly once.
	decoded := map[string]int{}
	for _, lit := range literalRE.FindAllString(evil, -1) {
		var s string
		if err := json.Unmarshal([]byte(lit), &s); err != nil {
			t.Fatalf("literal %s is not a valid string: %v", lit, err)
		}
		decoded[s]++
	}
	for _, s := range texts {
		if decoded[s] == 0 {
			t.Errorf("attack text %q does not decode back from a literal", s)
		}
	}
	rest := outsideLiterals(evil)
	for _, tag := range []string{"T1", "P1", "F1", "C1", "L1", "X1", "X2", "H1", "H2", "R1", "R2", "H3", "M1", "M2", "M3", "M4", "S1", "S2"} {
		if !strings.Contains(evil, tag) {
			t.Errorf("hostile text %s is missing from the output", tag)
		}
		if strings.Contains(rest, tag) {
			t.Errorf("hostile text %s is outside a string literal", tag)
		}
	}
	// No raw markup character from model text inside any literal either.
	for _, lit := range literalRE.FindAllString(evil, -1) {
		if strings.ContainsAny(lit, "<>&") {
			t.Errorf("literal holds a raw markup character: %s", lit)
		}
	}
	if strings.Count(rest, "{") != strings.Count(rest, "}") || strings.Count(rest, "(") != strings.Count(rest, ")") {
		t.Errorf("braces or parentheses outside literals do not balance")
	}
	for _, bad := range []string{"`", "${", "<script", "</script", "alert", "&amp;"} {
		if strings.Contains(rest, bad) {
			t.Errorf("%q appears outside a string literal", bad)
		}
	}
	// Every '<' outside literals opens a known element or fragment.
	known := regexp.MustCompile(`</?(ResearchPageShell|ResearchBottomLine|SectionHeader|Panel|ul|li|p)\b|</?>`)
	for _, line := range strings.Split(rest, "\n") {
		for i := 0; i < len(line); i++ {
			if line[i] == '<' && !known.MatchString(line[i:]) {
				t.Errorf("unexpected '<' outside literals: %s", line)
			}
		}
	}
}

