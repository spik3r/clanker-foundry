func TestForbiddenConstructsAbsent(t *testing.T) {
	for name, raw := range map[string]string{"example": string(example(t)), "good": good} {
		out := jsxOf(t, raw)
		for _, re := range forbidden {
			if loc := re.FindStringIndex(out); loc != nil {
				t.Errorf("%s: output contains forbidden %s: %q", name, re, out[loc[0]:loc[1]])
			}
		}
	}
	// Even for the hostile model, nothing forbidden appears outside literals.
	raw, _ := hostile(t, true)
	rest := outsideLiterals(jsxOf(t, raw))
	for _, re := range forbidden {
		if re.MatchString(rest) {
			t.Errorf("hostile model: %s appears outside literals", re)
		}
	}
}

var (
	importLine = regexp.MustCompile(`(?m)^\s*(?:import|export)\b.*$`)
	adapterRE  = regexp.MustCompile(`^import \{ ([A-Za-z, ]+) \} from "\.\./researchPageParts";$`)
	fromRE     = regexp.MustCompile(`\bfrom\s+"([^"]*)"`)
)

func TestOnlyAllowedImports(t *testing.T) {
	for name, raw := range map[string]string{"example": string(example(t)), "good": good} {
		out := jsxOf(t, raw)
		imports := 0
		for _, line := range importLine.FindAllString(out, -1) {
			line = strings.TrimSpace(line)
			switch {
			case strings.HasPrefix(line, "export default function "):
			case adapterRE.MatchString(line):
				imports++
				for _, n := range strings.Split(adapterRE.FindStringSubmatch(line)[1], ", ") {
					if !contains(AdapterExports, n) {
						t.Errorf("%s: imports %q, which the adapter contract does not list", name, n)
					}
				}
			case line == `import { Show } from "solid-js";`: // allowed by the contract; the current output needs none
			default:
				t.Errorf("%s: unexpected import or export %q", name, line)
			}
		}
		if imports != 1 {
			t.Errorf("%s: %d adapter imports, want 1", name, imports)
		}
		for _, m := range fromRE.FindAllStringSubmatch(outsideImports(out), -1) {
			t.Errorf("%s: module reference %q outside an import line", name, m[1])
		}
		if strings.Count(out, "export default") != 1 || strings.Count(out, "export ") != 1 {
			t.Errorf("%s: want exactly one export, the default component", name)
		}
	}
}

// outsideImports returns the source without its import lines.
func outsideImports(src string) string { return importLine.ReplaceAllString(src, "") }

func TestEverySlotIsReferencedOnce(t *testing.T) {
	for name, raw := range map[string]string{"example": string(example(t)), "good": good} {
		g := generated(t, raw)
		out := string(g.Files[FileJSX])
		var ids []string
		if err := json.Unmarshal(g.Files[FileSlots], &ids); err != nil {
			t.Fatal(err)
		}
		if len(ids) == 0 {
			t.Fatalf("%s: no slots", name)
		}
		last := -1
		for _, id := range ids {
			ref := "renderSlot(props.slots." + id + ")"
			if n := strings.Count(out, ref); n != 1 {
				t.Errorf("%s: slot %s is referenced %d times", name, id, n)
			}
			at := strings.Index(out, ref)
			if at < last {
				t.Errorf("%s: slot %s is out of order in the module", name, id)
			}
			last = at
		}
		if n := strings.Count(out, "props.slots."); n != len(ids) {
			t.Errorf("%s: %d slot references, slots.json lists %d", name, n, len(ids))
		}
		seen := map[string]bool{}
		for _, id := range ids {
			if seen[id] {
				t.Errorf("%s: slots.json lists %s twice", name, id)
			}
			seen[id] = true
		}
		if want := "[\n  \"" + strings.Join(ids, "\",\n  \"") + "\"\n]\n"; string(g.Files[FileSlots]) != want {
			t.Errorf("%s: slots.json is not a two-space indented array with a trailing newline: %q", name, g.Files[FileSlots])
		}
	}
}

func TestPassThroughProps(t *testing.T) {
	out := jsxOf(t, string(example(t)))
	for _, want := range []string{"freshness={props.freshness}", "provenance={props.provenance}", "metrics={props.metrics}", `class={"stat-research-page" + (props.class ? " " + props.class : "")}`} {
		if strings.Count(out, want) != 1 {
			t.Errorf("want exactly one %q", want)
		}
	}
	// Only these props and slots are read.
	for _, m := range regexp.MustCompile(`props\.([A-Za-z]+)`).FindAllStringSubmatch(out, -1) {
		switch m[1] {
		case "freshness", "provenance", "metrics", "class", "slots":
		default:
			t.Errorf("reads props.%s", m[1])
		}
	}
}

func TestExampleTextIsPreserved(t *testing.T) {
	// Every text of the model appears once as a string literal in the module.
	m, err := Decode(example(t))
	if err != nil {
		t.Fatal(err)
	}
	var texts []string
	texts = append(texts, m.Title, m.Purpose, m.BottomLine.Finding, m.BottomLine.Confidence, m.BottomLine.Limitation)
	texts = append(texts, m.BottomLine.Context...)
	for _, s := range m.Sections {
		for _, it := range s.Items {
			texts = append(texts, it.Title, it.Description)
			texts = append(texts, it.Points...)
			texts = append(texts, it.Paragraphs...)
		}
	}
	decoded := map[string]int{}
	for _, lit := range literalRE.FindAllString(jsxOf(t, string(example(t))), -1) {
		var s string
		if err := json.Unmarshal([]byte(lit), &s); err != nil {
			t.Fatal(err)
		}
		decoded[s]++
	}
	n := 0
	for _, s := range texts {
		if s == "" {
			continue
		}
		n++
		if decoded[s] == 0 {
			t.Errorf("text %q is missing from the module", s)
		}
	}
	if n < 15 {
		t.Errorf("only %d texts checked", n)
	}
}
