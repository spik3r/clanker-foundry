package researchpage

import (
	"strings"

	"github.com/spik3r/clanker-foundry/modeling/diagram/contract"
	"github.com/spik3r/clanker-foundry/modeling/diagram/internal/jsxemit"
)

// Output file names.
const (
	FileJSX   = "ResearchPage.jsx"
	FileSlots = "slots.json"
	FileModel = "model.json"
)

// Adapter is the one module the component imports from besides solid-js. The
// host supplies it; it must export the names in AdapterExports.
const Adapter = "../researchPageParts"

// AdapterExports lists the names the adapter module must export, sorted. The
// component imports only those it uses.
var AdapterExports = []string{"Panel", "ResearchBottomLine", "ResearchPageShell", "SectionHeader"}

// ComponentSuffix follows the model id in the exported component's name.
const ComponentSuffix = "Content"

// RenderJSX writes ResearchPage.jsx for a validated, normalized model. digest
// is the canonical model digest named in the header line.
func RenderJSX(m Model, g contract.Generator, digest string) []byte {
	w := &jsxemit.Writer{}
	slots := m.SlotIDs()
	uses := map[string]bool{"ResearchBottomLine": true, "ResearchPageShell": true}
	for _, sec := range m.Sections {
		for _, it := range sec.Items {
			switch it.Kind {
			case KindPanel:
				uses["Panel"] = true
			case KindHeading:
				uses["SectionHeader"] = true
			case KindMethodPanel:
				uses["Panel"], uses["SectionHeader"] = true, true
			}
		}
	}
	var names []string
	for _, n := range AdapterExports {
		if uses[n] {
			names = append(names, n)
		}
	}
	w.Line("// Code generated by " + g.ID + " " + g.Version + " from model " + digest + ". DO NOT EDIT.")
	w.Line("")
	w.Line("import { " + strings.Join(names, ", ") + " } from " + jsxemit.String(Adapter) + ";")
	w.Line("")
	if len(slots) > 0 {
		w.Line("function renderSlot(value) {")
		w.Line(`  return typeof value === "function" ? value() : value;`)
		w.Line("}")
		w.Line("")
	}
	w.Line("export default function " + m.ID + ComponentSuffix + "(props) {")
	w.Depth++
	w.Line("return (")
	w.Depth++
	w.Line("<ResearchPageShell")
	w.Depth++
	if m.Class != "" {
		w.Line("class={" + jsxemit.String(m.Class) + ` + (props.class ? " " + props.class : "")}`)
	} else {
		w.Line("class={props.class}")
	}
	w.Line("title={" + jsxemit.String(m.Title) + "}")
	w.Line("purpose={" + jsxemit.String(m.Purpose) + "}")
	w.Line("status={" + jsxemit.String(m.Status) + "}")
	w.Line("freshness={props.freshness}")
	w.Line("provenance={props.provenance}")
	w.Line("summary={")
	w.Depth++
	writeBottomLine(w, m)
	w.Depth--
	w.Line("}")
	for _, sec := range m.Sections {
		w.Line(sec.Tab + "={")
		w.Depth++
		w.Line("<>")
		w.Depth++
		for _, it := range sec.Items {
			writeItem(w, it)
		}
		w.Depth--
		w.Line("</>")
		w.Depth--
		w.Line("}")
	}
	w.Depth--
	w.Line("/>")
	w.Depth--
	w.Line(");")
	w.Depth--
	w.Line("}")
	return []byte(w.String())
}

func writeBottomLine(w *jsxemit.Writer, m Model) {
	b := m.BottomLine
	w.Line("<ResearchBottomLine")
	w.Depth++
	w.Line("status={" + jsxemit.String(m.Status) + "}")
	w.Line("finding={" + jsxemit.String(b.Finding) + "}")
	w.Line("confidence={" + jsxemit.String(b.Confidence) + "}")
	w.Line("metrics={props.metrics}")
	w.Line("limitation={" + jsxemit.String(b.Limitation) + "}")
	w.Depth--
	if len(b.Context) == 0 {
		w.Line("/>")
		return
	}
	w.Line(">")
	w.Depth++
	for _, p := range b.Context {
		w.Line("<p>{" + jsxemit.String(p) + "}</p>")
	}
	w.Depth--
	w.Line("</ResearchBottomLine>")
}

func slotExpr(id string) string { return "{renderSlot(props.slots." + id + ")}" }

func header(it Item) string {
	s := "<SectionHeader" + jsxemit.Attr("title", it.Title)
	if it.Description != "" {
		s += jsxemit.Attr("description", it.Description)
	}
	return s + " />"
}

func writeItem(w *jsxemit.Writer, it Item) {
	switch it.Kind {
	case KindSlot:
		w.Line(slotExpr(it.ID))
	case KindPanel:
		w.Line("<Panel>" + slotExpr(it.Slot) + "</Panel>")
	case KindHeading:
		w.Line(header(it))
	case KindMethodPanel:
		w.Line("<Panel>")
		w.Depth++
		w.Line(header(it))
		w.Line("<ul>")
		w.Depth++
		for _, p := range it.Points {
			w.Line("<li>{" + jsxemit.String(p) + "}</li>")
		}
		w.Depth--
		w.Line("</ul>")
		w.Depth--
		w.Line("</Panel>")
	case KindProse:
		for _, p := range it.Paragraphs {
			w.Line("<p>{" + jsxemit.String(p) + "}</p>")
		}
	}
}
