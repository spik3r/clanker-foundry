// Label budgets are counts of characters (runes). There is no font
// measurement, so a label of wide characters can still overflow its shape.
const (
	taskBudget    = 20
	taskLines     = 3
	eventBudget   = 22
	eventLines    = 2
	gatewayBudget = 10
	gatewayLines  = 3
	laneBudget    = 18
	laneLines     = 3
	lineHeight    = 14
	titleCharsPx  = 9 // assumed width of one title character, for truncation
)

// esc escapes text for XML character data and attribute values.
func esc(s string) string {
	var b strings.Builder
	for _, r := range s {
		switch r {
		case '&':
			b.WriteString("&amp;")
		case '<':
			b.WriteString("&lt;")
		case '>':
			b.WriteString("&gt;")
		case '"':
			b.WriteString("&quot;")
		case '\'':
			b.WriteString("&apos;")
		default:
			b.WriteRune(r)
		}
	}
	return b.String()
}

// wrap breaks s into at most maxLines lines of at most budget characters,
// filling lines greedily word by word. A word longer than a line is cut into
// line-sized pieces. Text beyond maxLines is dropped and the last line ends
// with an ellipsis.
func wrap(s string, budget, maxLines int) []string {
	var lines []string
	cur := ""
	curLen := 0
	flush := func() {
		if cur != "" {
			lines = append(lines, cur)
			cur, curLen = "", 0
		}
	}
	for _, w := range strings.Fields(s) {
		r := []rune(w)
		for len(r) > budget {
			flush()
			lines = append(lines, string(r[:budget]))
			r = r[budget:]
		}
		switch {
		case cur == "":
			cur, curLen = string(r), len(r)
		case curLen+1+len(r) <= budget:
			cur += " " + string(r)
			curLen += 1 + len(r)
		default:
			flush()
			cur, curLen = string(r), len(r)
		}
	}
	flush()
	if len(lines) > maxLines {
		lines = lines[:maxLines]
		last := []rune(lines[maxLines-1])
		if len(last) >= budget {
			last = last[:budget-1]
		}
		lines[maxLines-1] = strings.TrimRight(string(last), " ") + "…"
	}
	return lines
}

// truncate shortens s to at most n characters, ending with an ellipsis.
func truncate(s string, n int) string {
	r := []rune(s)
	if len(r) <= n {
		return s
	}
	return string(r[:n-1]) + "…"
}

func itoa(n int) string { return strconv.Itoa(n) }

// textBlock writes centred (or left aligned) lines with explicit positions.
func textBlock(b *strings.Builder, class, anchor string, x, firstY int, lines []string) {
	if len(lines) == 0 {
		return
	}
	fmt.Fprintf(b, `<text class="%s" text-anchor="%s">`, class, anchor)
	for i, ln := range lines {
		fmt.Fprintf(b, `<tspan x="%d" y="%d">%s</tspan>`, x, firstY+i*lineHeight, esc(ln))
	}
	b.WriteString("</text>\n")
}

const svgStyle = `.bg{fill:#fff}
.lane{fill:#fff;stroke:#8a8f98;stroke-width:1}
.strip{fill:#eef1f5;stroke:#8a8f98;stroke-width:1}
.lane-title{font-weight:bold;fill:#222}
.title{font-size:16px;font-weight:bold;fill:#222}
.shape{fill:#fff;stroke:#222;stroke-width:1.5}
.start{stroke-width:1.5}
.end{stroke-width:4}
.mark{fill:none;stroke:#222;stroke-width:2.5}
.label{fill:#222}
.flow{fill:none;stroke:#444;stroke-width:1.5}
.arrow{fill:#444}
.flow-label{font-size:11px;fill:#222}`

// SVG renders the layout as an inert picture: no script, no event
// attributes, no external references and no embedded fonts or images.
func SVG(m Model, l Layout, g contract.Generator) []byte {
	var b strings.Builder
	w, h := l.Width, l.Height
	b.WriteString(`<?xml version="1.0" encoding="UTF-8"?>` + "\n")
	fmt.Fprintf(&b, `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 %d %d" width="%d" height="%d" font-family="Helvetica, Arial, sans-serif" font-size="12" role="img">`+"\n", w, h, w, h)
	fmt.Fprintf(&b, "<title>%s</title>\n", esc(m.Title))
	fmt.Fprintf(&b, "<desc>%s diagram %s, generated by %s %s</desc>\n", Profile, esc(m.ID), g.ID, g.Version)
	b.WriteString(`<defs><marker id="arrow" viewBox="0 0 10 10" refX="10" refY="5" markerWidth="9" markerHeight="9" markerUnits="userSpaceOnUse" orient="auto"><path class="arrow" d="M0 0 L10 5 L0 10 z"/></marker></defs>` + "\n")
	b.WriteString("<style>\n" + svgStyle + "\n</style>\n")
	fmt.Fprintf(&b, `<rect class="bg" x="0" y="0" width="%d" height="%d"/>`+"\n", w, h)

	title := truncate(m.Title, max(8, (w-2*margin)/titleCharsPx))
	fmt.Fprintf(&b, `<text class="title" x="%d" y="%d">%s</text>`+"\n", l.Title.X, l.Title.Y, esc(title))

	for _, ln := range l.Lanes {
		bx := ln.Box
		fmt.Fprintf(&b, `<g class="lane-group"><rect class="lane" data-lane="%s" x="%d" y="%d" width="%d" height="%d"/>`, esc(ln.Lane.ID), bx.X, bx.Y, bx.W, bx.H)
		fmt.Fprintf(&b, `<rect class="strip" x="%d" y="%d" width="%d" height="%d"/>`+"\n", bx.X, bx.Y, laneStripW, bx.H)
		lines := wrap(ln.Lane.Label, laneBudget, laneLines)
		textBlock(&b, "lane-title", "start", bx.X+8, bx.Y+bx.H/2-(len(lines)-1)*lineHeight/2+4, lines)
		b.WriteString("</g>\n")
	}

	for _, f := range l.Flows {
		var d strings.Builder
		for i, p := range f.Points {
			if i == 0 {
				d.WriteString("M")
			} else {
				d.WriteString(" L")
			}
			fmt.Fprintf(&d, "%d %d", p.X, p.Y)
		}
		fmt.Fprintf(&b, `<path class="flow" data-id="%s" data-from="%s" data-to="%s" d="%s" marker-end="url(#arrow)"/>`+"\n",
			esc(f.Flow.ID), esc(f.Flow.From), esc(f.Flow.To), d.String())
	}

	for _, n := range l.Nodes {
		bx := n.Box
		fmt.Fprintf(&b, `<g data-id="%s" data-kind="%s">`, esc(n.Node.ID), n.Node.Kind)
		var lines []string
		switch n.Node.Kind {
		case KindTask:
			fmt.Fprintf(&b, `<rect class="shape" x="%d" y="%d" width="%d" height="%d" rx="10"/>`+"\n", bx.X, bx.Y, bx.W, bx.H)
			lines = wrap(n.Node.Label, taskBudget, taskLines)
			textBlock(&b, "label", "middle", n.CX, n.CY-(len(lines)-1)*lineHeight/2+4, lines)
		case KindStart, KindEnd:
			fmt.Fprintf(&b, `<circle class="shape %s" cx="%d" cy="%d" r="%d"/>`+"\n", n.Node.Kind, n.CX, n.CY, bx.W/2)
			lines = wrap(n.Node.Label, eventBudget, eventLines)
			textBlock(&b, "label", "middle", n.CX, bx.Y+bx.H+16, lines)
		default:
			r := bx.W / 2
			fmt.Fprintf(&b, `<polygon class="shape" points="%d,%d %d,%d %d,%d %d,%d"/>`,
				n.CX, n.CY-r, n.CX+r, n.CY, n.CX, n.CY+r, n.CX-r, n.CY)
			if n.Node.Kind == KindExclusive {
				fmt.Fprintf(&b, `<path class="mark" d="M%d %d L%d %d M%d %d L%d %d"/>`+"\n",
					n.CX-9, n.CY-9, n.CX+9, n.CY+9, n.CX+9, n.CY-9, n.CX-9, n.CY+9)
			} else {
				fmt.Fprintf(&b, `<path class="mark" d="M%d %d L%d %d M%d %d L%d %d"/>`+"\n",
					n.CX-10, n.CY, n.CX+10, n.CY, n.CX, n.CY-10, n.CX, n.CY+10)
			}
			// Above and left of the diamond: exits use its top, right and
			// bottom, and entries its left corner.
			lines = wrap(n.Node.Label, gatewayBudget, gatewayLines)
			textBlock(&b, "label", "end", n.CX-18, n.CY-28-(len(lines)-1)*lineHeight, lines)
		}
		b.WriteString("</g>\n")
	}

	for _, f := range l.Flows {
		if f.Label == nil {
			continue
		}
		bx := f.Label.Box
		fmt.Fprintf(&b, `<text class="flow-label" data-flow="%s" data-anchor="%d" data-box="%d %d %d %d" x="%d" y="%d">%s</text>`+"\n",
			esc(f.Flow.ID), f.Label.Anchor, bx.X, bx.Y, bx.W, bx.H, bx.X+2, bx.Y+bx.H-1, esc(f.Label.Text))
	}
	b.WriteString("</svg>\n")
	return []byte(b.String())
}
