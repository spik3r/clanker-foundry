package traceability

import (
	"bytes"
	"encoding/json"
	"fmt"
	"html"
	"strings"
)

// JSON renders the report as indented JSON with a trailing newline.
func (r Report) JSON() ([]byte, error) {
	var b bytes.Buffer
	enc := json.NewEncoder(&b)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(r); err != nil {
		return nil, err
	}
	return b.Bytes(), nil
}

// cell makes text safe inside a Markdown table cell.
func cell(s string) string {
	s = strings.ReplaceAll(s, "\\", "\\\\")
	s = strings.ReplaceAll(s, "|", "\\|")
	s = strings.ReplaceAll(s, "\t", " ")
	s = strings.ReplaceAll(s, "&", "&amp;")
	s = strings.ReplaceAll(s, "<", "&lt;")
	s = strings.ReplaceAll(s, ">", "&gt;")
	return s
}

func list(items []string) string {
	if len(items) == 0 {
		return "—"
	}
	return strings.Join(items, ", ")
}

// Markdown renders a human-readable trace with the same content as JSON.
func (r Report) Markdown() []byte {
	var b strings.Builder
	p := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }
	p("# Requirements trace: %s\n\n", r.Inputs.ModelID)
	p("Generated by `go run ./cmd/modeltrace generate`. Do not edit by hand.\n\n")
	p("%s Mode `%s`, authority `%s`.\n\n", r.Notice, r.Mode, r.Authority)
	p("| Input | Identity |\n|---|---|\n")
	p("| Requirements (`%s`) | normalized SHA-256 `%s` |\n", r.Inputs.RequirementsFormat, r.Inputs.RequirementsDigest)
	p("| Model `%s` | canonical SHA-256 `%s` |\n", r.Inputs.ModelID, r.Inputs.ModelDigest)
	p("| Acceptance catalog (`%s`) | file SHA-256 `%s` |\n\n", r.Inputs.AcceptanceCatalog, r.Inputs.CatalogSHA256)

	s := r.Summary
	p("## Summary\n\n")
	p("- Requirements: %d (%d linked, %d incomplete)\n", s.Requirements, s.Linked, s.Incomplete)
	p("- Model elements: %d (%d untraced)\n", s.ModelElements, s.UntracedModelElements)
	p("- Acceptance cases: %d (%d pending, %d not linked to any requirement)\n\n", s.AcceptanceCases, s.PendingAcceptanceCases, s.UnlinkedAcceptanceCases)
	p("`linked` means the requirement has at least one model link and at least one executable acceptance link. It is not a verdict on correctness.\n\n")

	p("## Requirements\n\n| ID | Requirement | Status | Model links | Acceptance cases |\n|---|---|---|---|---|\n")
	for _, q := range r.Requirements {
		models := []string{}
		for _, l := range q.ModelLinks {
			models = append(models, "`"+l.ID+"`")
		}
		cases := []string{}
		for _, c := range q.AcceptanceLinks {
			x := "`" + c.CaseID + "`"
			if c.ExecutionStatus != "executable" {
				x += " (" + c.ExecutionStatus + ")"
			}
			cases = append(cases, x)
		}
		status := q.Status
		if len(q.Gaps) > 0 {
			status += ": " + strings.Join(q.Gaps, ", ")
		}
		p("| %s | **%s**<br>%s | %s | %s | %s |\n", q.ID, cell(q.Title), cell(q.Statement), status, list(models), list(cases))
	}

	p("\n## Gaps\n\n")
	gaps := 0
	for _, q := range r.Requirements {
		for _, g := range q.Gaps {
			p("- %s: %s\n", q.ID, gapText(g))
			gaps++
		}
	}
	for _, e := range r.ModelElements {
		if e.Untraced() {
			p("- Model %s `%s` is not linked by any requirement.\n", e.Kind, e.ID)
			gaps++
		}
	}
	for _, c := range r.AcceptanceCases {
		if len(c.TracedBy) == 0 {
			p("- Acceptance case `%s` (%s) is not linked to any requirement.\n", c.CaseID, cell(c.Name))
			gaps++
		}
	}
	if gaps == 0 {
		p("None.\n")
	}

	p("\n## Model elements\n\n| Kind | ID | Detail | Traced by |\n|---|---|---|---|\n")
	for _, e := range r.ModelElements {
		by := list(e.TracedBy)
		if e.Kind == KindModelRequirement {
			by = "direct: " + list(e.TracedBy) + "; via guard: " + list(e.TracedViaGuard)
		}
		p("| %s | `%s` | %s | %s |\n", e.Kind, e.ID, cell(e.Detail), by)
	}

	p("\n## Acceptance cases\n\n| Case | Name | Status | Traced by |\n|---|---|---|---|\n")
	for _, c := range r.AcceptanceCases {
		p("| `%s` | %s | %s | %s |\n", c.CaseID, cell(c.Name), c.ExecutionStatus, list(c.TracedBy))
	}
	return []byte(b.String())
}

func gapText(g string) string {
	switch g {
	case GapNoModelLink:
		return "no model element is linked."
	case GapNoAcceptanceLink:
		return "no acceptance case is linked."
	case GapNoExecutableAcceptance:
		return "every linked acceptance case is pending in the catalog."
	}
	return g
}

// SVG renders an inert three-column view: model elements, requirements and
// acceptance cases, with one line per declared link. It is a SysML-inspired
// requirement diagram sketch, not a SysML or UML conformant diagram.
func (r Report) SVG() []byte {
	const (
		rowH   = 22
		top    = 78
		colW   = 250
		gap    = 120
		leftX  = 20
		midX   = leftX + colW + gap
		rightX = midX + colW + gap
		boxH   = 18
	)
	width := rightX + colW + 20
	esc := xmlText

	elY := map[string]int{}
	elements := []ElementTrace{}
	for _, e := range r.ModelElements {
		if e.Kind == KindModelRequirement {
			continue // shown in the model element table; guards carry the link
		}
		elY[e.Kind+":"+e.ID] = top + len(elements)*rowH
		elements = append(elements, e)
	}
	reqY := map[string]int{}
	for i, q := range r.Requirements {
		reqY[q.ID] = top + i*rowH*2
	}
	caseY := map[string]int{}
	for i, c := range r.AcceptanceCases {
		caseY[c.CaseID] = top + i*rowH
	}
	rows := len(elements)
	if n := len(r.Requirements) * 2; n > rows {
		rows = n
	}
	if n := len(r.AcceptanceCases); n > rows {
		rows = n
	}
	height := top + rows*rowH + 60

	var b strings.Builder
	p := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }
	p(`<svg xmlns="http://www.w3.org/2000/svg" width="%d" height="%d" viewBox="0 0 %d %d" role="img" aria-labelledby="title desc">`+"\n", width, height, width, height)
	p(`<title id="title">Requirements trace: %s</title>`+"\n", esc(r.Inputs.ModelID))
	p(`<desc id="desc">Declared links between model elements, requirements and acceptance cases. Example only; links are not evidence of correctness. Not a SysML or UML conformant diagram.</desc>` + "\n")
	p(`<style>text{font-family:monospace;font-size:11px;fill:#1f2328}.h{font-size:13px;font-weight:bold}.n{font-size:10px;fill:#57606a}rect{stroke:#57606a;stroke-width:1}.ok{fill:#dafbe1}.gap{fill:#fff1e5;stroke:#bc4c00;stroke-dasharray:4 2}.el{fill:#ddf4ff}.un{fill:#ffebe9;stroke:#cf222e;stroke-dasharray:4 2}.cs{fill:#f6f8fa}.pend{fill:#f6f8fa;stroke-dasharray:4 2}line{stroke:#8c959f;stroke-width:1}</style>` + "\n")
	p(`<rect x="0" y="0" width="%d" height="%d" fill="#ffffff" stroke="none"/>`+"\n", width, height)
	p(`<text class="h" x="%d" y="24">Requirements trace: %s (example only, authority none)</text>`+"\n", leftX, esc(r.Inputs.ModelID))
	p(`<text class="h" x="%d" y="58">Model elements</text><text class="h" x="%d" y="58">Requirements</text><text class="h" x="%d" y="58">Acceptance cases</text>`+"\n", leftX, midX, rightX)

	for _, q := range r.Requirements {
		y := reqY[q.ID] + boxH/2
		for _, l := range q.ModelLinks {
			if ey, ok := elY[l.Kind+":"+l.ID]; ok {
				p(`<line x1="%d" y1="%d" x2="%d" y2="%d"/>`+"\n", leftX+colW, ey+boxH/2, midX, y)
			}
		}
		for _, c := range q.AcceptanceLinks {
			p(`<line x1="%d" y1="%d" x2="%d" y2="%d"/>`+"\n", midX+colW, y, rightX, caseY[c.CaseID]+boxH/2)
		}
	}
	for _, e := range elements {
		cls := "el"
		if e.Untraced() {
			cls = "un"
		}
		y := elY[e.Kind+":"+e.ID]
		p(`<rect class="%s" x="%d" y="%d" width="%d" height="%d"/><text x="%d" y="%d">%s %s</text>`+"\n", cls, leftX, y, colW, boxH, leftX+4, y+13, esc(abbrev(e.Kind)), esc(e.ID))
	}
	for _, q := range r.Requirements {
		cls := "ok"
		if q.Status != StatusLinked {
			cls = "gap"
		}
		y := reqY[q.ID]
		label := q.ID + " " + q.Title
		if r := []rune(label); len(r) > 36 {
			label = string(r[:35]) + "…"
		}
		p(`<rect class="%s" x="%d" y="%d" width="%d" height="%d"/><text x="%d" y="%d">%s</text>`+"\n", cls, midX, y, colW, boxH, midX+4, y+13, esc(label))
		if len(q.Gaps) > 0 {
			p(`<text class="n" x="%d" y="%d">%s</text>`+"\n", midX+4, y+boxH+12, esc(strings.Join(q.Gaps, ", ")))
		}
	}
	for _, c := range r.AcceptanceCases {
		cls := "cs"
		if c.ExecutionStatus != "executable" {
			cls = "pend"
		}
		if len(c.TracedBy) == 0 {
			cls = "un"
		}
		y := caseY[c.CaseID]
		label := c.CaseID
		if c.ExecutionStatus != "executable" {
			label += " (" + c.ExecutionStatus + ")"
		}
		p(`<rect class="%s" x="%d" y="%d" width="%d" height="%d"/><text x="%d" y="%d">%s</text>`+"\n", cls, rightX, y, colW, boxH, rightX+4, y+13, esc(label))
	}
	p(`<text class="n" x="%d" y="%d">Green: model and executable acceptance links present. Orange dashed: requirement with gaps. Red dashed: not linked. Grey dashed: pending case.</text>`+"\n", leftX, height-30)
	p(`<text class="n" x="%d" y="%d">Model requirements are reached through the guards that declare them; see trace.md. Lines are declared links, not verification.</text>`+"\n", leftX, height-14)
	p("</svg>\n")
	return []byte(b.String())
}

// xmlText escapes text for SVG and replaces each character XML 1.0 cannot
// carry (controls other than tab, newline and carriage return, surrogates,
// U+FFFE and U+FFFF) with U+FFFD. This changes only the drawing. The report,
// Markdown and the requirements digest keep the exact source text.
func xmlText(s string) string {
	return html.EscapeString(strings.Map(func(r rune) rune {
		switch {
		case r == 0x9 || r == 0xA || r == 0xD:
			return r
		case r < 0x20, r == 0xFFFE, r == 0xFFFF, r >= 0xD800 && r <= 0xDFFF:
			return 0xFFFD
		}
		return r
	}, s))
}

func abbrev(kind string) string {
	switch kind {
	case KindState:
		return "[state]"
	case KindTransition:
		return "[trans]"
	case KindGuard:
		return "[guard]"
	}
	return "[" + kind + "]"
}
