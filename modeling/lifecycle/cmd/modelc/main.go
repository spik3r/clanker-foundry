// modelc is an offline example generator, not a trusted execution launcher.
package main

import (
	"bytes"
	"crypto/rand"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"errors"
	"fmt"
	"github.com/spik3r/clanker-foundry/modeling/lifecycle/canonical"
	"github.com/spik3r/clanker-foundry/modeling/lifecycle/compiler"
	"github.com/spik3r/clanker-foundry/modeling/lifecycle/jsonformat"
	"github.com/spik3r/clanker-foundry/modeling/lifecycle/model"
	"github.com/spik3r/clanker-foundry/modeling/lifecycle/views"
	"io"
	"os"
	"runtime"
	"sort"
	"strings"
)

var names = []string{"decision-table.json", "decision.svg", "lifecycle.go", "model_paths_test.go", "trace.json"}

func fail(s string) error { return errors.New(s) }
func regular(r *os.Root, path string, limit int64) ([]byte, error) {
	s, e := r.Lstat(path)
	if e != nil {
		return nil, e
	}
	if !s.Mode().IsRegular() || s.Size() > limit {
		return nil, fail("not a bounded regular file")
	}
	f, e := r.Open(path)
	if e != nil {
		return nil, e
	}
	defer f.Close()
	b, e := io.ReadAll(io.LimitReader(f, limit+1))
	if e != nil || int64(len(b)) > limit {
		return nil, fail("read limit")
	}
	return b, nil
}
func directory(r *os.Root, path string) error {
	s, e := r.Lstat(path)
	if e != nil {
		return e
	}
	if !s.IsDir() || s.Mode()&os.ModeSymlink != 0 {
		return fail("directory/symlink refusal")
	}
	return nil
}
func outputState(r *os.Root) (map[string][]byte, error) {
	got := map[string][]byte{}
	if e := directory(r, "generated"); e != nil {
		if os.IsNotExist(e) {
			return got, nil
		}
		return nil, e
	}
	f, e := r.Open("generated")
	if e != nil {
		return nil, e
	}
	entries, e := f.ReadDir(-1)
	f.Close()
	if e != nil {
		return nil, e
	}
	owned := map[string]bool{}
	for _, n := range names {
		owned[n] = true
	}
	for _, entry := range entries {
		n := entry.Name()
		s, e := r.Lstat("generated/" + n)
		if e != nil {
			return nil, e
		}
		if s.Mode()&os.ModeSymlink != 0 {
			return nil, fail("output symlink")
		}
		if !owned[n] {
			if strings.HasSuffix(n, ".go") || strings.HasPrefix(n, ".lifecycle-") {
				return nil, fail("stale or colliding output")
			}
			if s.Mode().IsRegular() {
				// Owned markers occur in the generated header. A large stale
				// artifact must not evade detection merely by exceeding the scan.
				f, e := r.Open("generated/" + n)
				if e != nil {
					return nil, e
				}
				b, e := io.ReadAll(io.LimitReader(f, 1<<20))
				f.Close()
				if e != nil {
					return nil, e
				}
				if bytes.Contains(b, []byte("Generated design intent; invented example")) || bytes.Contains(b, []byte("lifecycle-trace/v1")) || bytes.Contains(b, []byte("lifecycle-decision-table/v1")) {
					return nil, fail("stale owned output")
				}
			}
			continue
		}
		b, e := regular(r, "generated/"+n, 16<<20)
		if e != nil {
			return nil, e
		}
		got[n] = b
	}
	return got, nil
}
func previousOwned(got map[string][]byte) error {
	if len(got) == 0 {
		return nil
	}
	if len(got) != len(names) {
		return fail("partial output/collision; resolve explicitly")
	}
	var m struct {
		Schema    string                          `json:"schema"`
		Identity  views.Identity                  `json:"identity"`
		Artifacts []struct{ Path, SHA256 string } `json:"artifacts"`
	}
	if e := json.Unmarshal(got["trace.json"], &m); e != nil || m.Schema != "lifecycle-trace/v1" || m.Identity.GeneratorVersion != compiler.GeneratorVersion || m.Identity.ProfileVersion != model.ProfileVersion || len(m.Artifacts) != 4 {
		return fail("unowned trace collision")
	}
	seen := map[string]bool{}
	for _, a := range m.Artifacts {
		n := strings.TrimPrefix(a.Path, "generated/")
		if a.Path != "generated/"+n || n == "trace.json" || seen[n] || got[n] == nil {
			return fail("trace path collision")
		}
		h := sha256.Sum256(got[n])
		if a.SHA256 != hex.EncodeToString(h[:]) {
			return fail("modified output; refusing overwrite")
		}
		seen[n] = true
	}
	if len(seen) != 4 || !bytes.HasPrefix(got["lifecycle.go"], []byte("// Code generated by "+compiler.GeneratorVersion)) {
		return fail("unowned output collision")
	}
	// Reconstruct the previous trace from its validated decision model. Trace
	// cannot hash itself; this independently checks its exact canonical bytes.
	var table struct {
		Schema   string         `json:"schema"`
		Identity views.Identity `json:"identity"`
		Model    model.Model    `json:"model"`
	}
	if e := json.Unmarshal(got["decision-table.json"], &table); e != nil || table.Schema != "lifecycle-decision-table/v1" || table.Identity != m.Identity {
		return fail("modified decision model")
	}
	digest, e := canonical.Digest(table.Model)
	if e != nil || digest != m.Identity.ModelDigest {
		return fail("modified decision digest")
	}
	view, e := views.Render(table.Model, table.Identity)
	if e != nil || !bytes.Equal(view.DecisionTable, got["decision-table.json"]) || !bytes.Equal(view.SVG, got["decision.svg"]) {
		return fail("modified prior views")
	}
	trace, e := views.Trace(table.Model, table.Identity, view, views.CodeArtifacts{Implementation: got["lifecycle.go"], DerivedTests: got["model_paths_test.go"]})
	if e != nil || !bytes.Equal(trace, got["trace.json"]) {
		return fail("modified trace; refusing overwrite")
	}
	return nil
}
func publish(r *os.Root, outputs map[string][]byte) error {
	if e := directory(r, "generated"); e != nil {
		if !os.IsNotExist(e) {
			return e
		}
		if e = r.Mkdir("generated", 0755); e != nil {
			return e
		}
	}
	staged := map[string]string{}
	defer func() {
		for _, p := range staged {
			_ = r.Remove(p)
		}
	}()
	for _, n := range names {
		var nonce [12]byte
		if _, e := rand.Read(nonce[:]); e != nil {
			return e
		}
		p := "generated/.lifecycle-" + hex.EncodeToString(nonce[:]) + ".tmp"
		f, e := r.OpenFile(p, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0644)
		if e != nil {
			return e
		}
		staged[n] = p
		if _, e = f.Write(outputs[n]); e != nil {
			f.Close()
			return e
		}
		if e = f.Sync(); e != nil {
			f.Close()
			return e
		}
		if e = f.Close(); e != nil {
			return e
		}
	}
	// Trace is last. Any interrupted multi-file update is detectable, not success.
	for _, n := range names {
		if e := r.Rename(staged[n], "generated/"+n); e != nil {
			return e
		}
		delete(staged, n)
	}
	return nil
}
func run(args []string) error {
	if len(args) != 1 || (args[0] != "validate" && args[0] != "generate" && args[0] != "check") {
		return fail("usage: modelc validate|generate|check (run from modeling/lifecycle)")
	}
	if runtime.Version() != compiler.ToolchainVersion {
		return fail("unsupported Go toolchain; no automatic download")
	}
	r, e := os.OpenRoot(".")
	if e != nil {
		return e
	}
	defer r.Close()
	mod, e := regular(r, "go.mod", 4096)
	if e != nil || !bytes.HasPrefix(mod, []byte("module github.com/spik3r/clanker-foundry/modeling/lifecycle\n")) {
		return fail("wrong module directory")
	}
	if e = directory(r, "examples"); e != nil {
		return e
	}
	source, e := regular(r, "examples/lifecycle.json", 1<<20)
	if e != nil {
		return e
	}
	m, e := jsonformat.Decode(source)
	if e != nil {
		return e
	}
	digest, e := canonical.Digest(m)
	if e != nil {
		return e
	}
	if args[0] == "validate" {
		fmt.Printf("valid model %s; source SHA256 %x; canonical model SHA256 %s\n", m.ID, sha256.Sum256(source), digest)
		return nil
	}
	code, tests, e := compiler.Generate(m)
	if e != nil {
		return e
	}
	id := views.Identity{ModelDigest: digest, FormatVersion: jsonformat.FormatVersion, ProfileVersion: model.ProfileVersion, GeneratorVersion: compiler.GeneratorVersion, ToolchainVersion: compiler.ToolchainVersion}
	view, e := views.Render(m, id)
	if e != nil {
		return e
	}
	trace, e := views.Trace(m, id, view, views.CodeArtifacts{Implementation: code, DerivedTests: tests})
	if e != nil {
		return e
	}
	outputs := map[string][]byte{"lifecycle.go": code, "model_paths_test.go": tests, "decision.svg": view.SVG, "decision-table.json": view.DecisionTable, "trace.json": trace}
	for _, b := range outputs {
		if len(b) > 16<<20 {
			return fail("generated artifact limit")
		}
	}
	got, e := outputState(r)
	if e != nil {
		return e
	}
	if args[0] == "check" {
		var drift []string
		for _, n := range names {
			if !bytes.Equal(got[n], outputs[n]) {
				drift = append(drift, n)
			}
		}
		if len(drift) > 0 {
			sort.Strings(drift)
			return fmt.Errorf("generated drift: %s", strings.Join(drift, ","))
		}
		fmt.Println("generated artifacts match; no writes")
		return nil
	}
	if e = previousOwned(got); e != nil {
		return e
	}
	same := len(got) == len(names)
	for _, n := range names {
		same = same && bytes.Equal(got[n], outputs[n])
	}
	if same {
		fmt.Println("generated artifacts unchanged; no writes")
		return nil
	}
	if e = publish(r, outputs); e != nil {
		return e
	}
	fmt.Printf("generated %d fixed artifacts for %s\n", len(names), m.ID)
	return nil
}
func main() {
	if e := run(os.Args[1:]); e != nil {
		fmt.Fprintln(os.Stderr, "modelc:", e)
		os.Exit(1)
	}
}
