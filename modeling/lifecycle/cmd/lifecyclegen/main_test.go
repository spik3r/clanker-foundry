const exampleModel = "../../examples/lifecycle.json"

func runContract(args ...string) (int, string, string) {
	var o, e bytes.Buffer
	code := contractMain(args, &o, &e)
	return code, o.String(), e.String()
}

func mustRead(t *testing.T, p string) []byte {
	t.Helper()
	b, err := os.ReadFile(p)
	if err != nil {
		t.Fatal(err)
	}
	return b
}

func TestContractGenerateCheckValidate(t *testing.T) {
	dir := t.TempDir()
	out := filepath.Join(dir, "out")
	code, vout, verr := runContract("validate", exampleModel)
	if code != 0 || verr != "" {
		t.Fatalf("validate: %d %q", code, verr)
	}
	if !regexp.MustCompile(`^\{"contract":"foundry-generator/v1","profile":"lifecycle/v1","sourceSHA256":"[0-9a-f]{64}","canonicalSHA256":"[0-9a-f]{64}"\}\n$`).MatchString(vout) {
		t.Fatalf("identity line: %q", vout)
	}
	code, gout, gerr := runContract("generate", exampleModel, out)
	if code != 0 || gout != vout || gerr != "" {
		t.Fatalf("generate: %d %q %q", code, gout, gerr)
	}
	entries, _ := os.ReadDir(out)
	var names []string
	for _, e := range entries {
		names = append(names, e.Name())
	}
	sort.Strings(names)
	want := "decision-table.json decision.svg foundry-manifest.json lifecycle.go model_paths_test.go"
	if strings.Join(names, " ") != want {
		t.Fatalf("files: %v", names)
	}
	code, cout, cerr := runContract("check", exampleModel, out)
	if code != 0 || cout != vout || cerr != "" {
		t.Fatalf("check: %d %q %q", code, cout, cerr)
	}
	// Generating over the existing OUT is refused.
	if code, o, e := runContract("generate", exampleModel, out); code != 2 || o != "" || e == "" {
		t.Fatalf("existing out: %d %q %q", code, o, e)
	}
	// Drift.
	if err := os.WriteFile(filepath.Join(out, "decision.svg"), []byte("x"), 0o644); err != nil {
		t.Fatal(err)
	}
	os.Remove(filepath.Join(out, "lifecycle.go"))
	os.WriteFile(filepath.Join(out, "extra.txt"), nil, 0o644)
	code, o, e := runContract("check", exampleModel, out)
	if code != 3 || o != "" {
		t.Fatalf("drift: %d %q", code, o)
	}
	for _, l := range []string{"drift: modified decision.svg", "drift: missing lifecycle.go", "drift: unexpected extra.txt"} {
		if !strings.Contains(e, l+"\n") {
			t.Fatalf("missing %q in %q", l, e)
		}
	}
	if code, o, e := runContract("check", exampleModel, filepath.Join(dir, "none")); code != 3 || o != "" || e != "drift: missing .\n" {
		t.Fatalf("absent: %d %q %q", code, o, e)
	}
}

func TestContractOutputs(t *testing.T) {
	dir := t.TempDir()
	out := filepath.Join(dir, "out")
	if code, _, e := runContract("generate", exampleModel, out); code != 0 {
		t.Fatal(e)
	}
	_, vout, _ := runContract("validate", exampleModel)
	canon := regexp.MustCompile(`"canonicalSHA256":"([0-9a-f]{64})"`).FindStringSubmatch(vout)[1]
	header := "// Code generated by lifecyclegen 1.0.0 from model " + canon + ". DO NOT EDIT.\n"
	for _, n := range []string{"lifecycle.go", "model_paths_test.go"} {
		b := mustRead(t, filepath.Join(out, n))
		if !bytes.HasPrefix(b, []byte(header+"// Code generated ")) {
			t.Fatalf("%s header: %q", n, b[:200])
		}
		f, err := format.Source(b)
		if err != nil || !bytes.Equal(f, b) {
			t.Fatalf("%s not gofmt-formatted: %v", n, err)
		}
	}
	// Legacy bytes unchanged apart from the prepended line.
	for _, n := range []string{"lifecycle.go", "model_paths_test.go", "decision.svg", "decision-table.json"} {
		legacy := mustRead(t, filepath.Join("../../generated", n))
		got := mustRead(t, filepath.Join(out, n))
		if strings.HasSuffix(n, ".go") {
			got = bytes.TrimPrefix(got, []byte(header))
		}
		if !bytes.Equal(legacy, got) {
			t.Fatalf("%s differs from legacy output", n)
		}
	}
	if _, err := os.Stat(filepath.Join(out, "trace.json")); err == nil {
		t.Fatal("trace.json emitted")
	}
	if m := mustRead(t, filepath.Join(out, "foundry-manifest.json")); !bytes.HasSuffix(m, []byte("}\n")) || !bytes.Contains(m, []byte(`"toolchain": "go1.27.3"`)) {
		t.Fatalf("manifest: %s", m)
	}
}

func TestContractWhitespaceKeepsCanonicalDigest(t *testing.T) {
	dir := t.TempDir()
	src := mustRead(t, exampleModel)
	spaced := filepath.Join(dir, "spaced.json")
	os.WriteFile(spaced, append(bytes.ReplaceAll(src, []byte(",\n"), []byte(" ,\n\n\t")), '\n', '\n'), 0o644)
	_, a, _ := runContract("validate", exampleModel)
	code, b, e := runContract("validate", spaced)
	if code != 0 {
		t.Fatal(e)
	}
	if a == b {
		t.Fatal("source digest should differ")
	}
	re := regexp.MustCompile(`"canonicalSHA256":"[0-9a-f]{64}"`)
	if re.FindString(a) != re.FindString(b) {
		t.Fatal("canonical digest changed with whitespace")
	}
	// Emitted bytes do not depend on source bytes or paths.
	o1, o2 := filepath.Join(dir, "o1"), filepath.Join(dir, "o2")
	runContract("generate", exampleModel, o1)
	runContract("generate", spaced, o2)
	for _, n := range []string{"decision-table.json", "decision.svg", "foundry-manifest.json", "lifecycle.go", "model_paths_test.go"} {
		if !bytes.Equal(mustRead(t, filepath.Join(o1, n)), mustRead(t, filepath.Join(o2, n))) {
			t.Fatalf("%s depends on source bytes", n)
		}
	}
}

func TestContractRefusals(t *testing.T) {
	dir := t.TempDir()
	bad := filepath.Join(dir, "bad.json")
	os.WriteFile(bad, []byte("{}"), 0o644)
	out := filepath.Join(dir, "out")
	for _, args := range [][]string{
		{"validate", bad}, {"generate", bad, out}, {"check", bad, out},
		{"validate", filepath.Join(dir, "missing.json")},
		{"validate", dir},
		{"generate", exampleModel, filepath.Join(dir, "no", "parent")},
		{}, {"bogus"}, {"--help"}, {"-h"}, {"validate", "a", "b"}, {"generate", "a"}, {"check", "a"},
		{"generate", "a", "b", "c"}, {"check", "a", "b", "c"}, {"bogus", "a", "b"},
	} {
		if code, o, e := runContract(args...); code != 2 || o != "" || e == "" {
			t.Errorf("%v: %d %q %q", args, code, o, e)
		}
	}
	if _, err := os.Lstat(out); err == nil {
		t.Fatal("invalid model created OUT")
	}
	// Existing file, empty directory and symlink are refused and untouched.
	file := filepath.Join(dir, "file")
	os.WriteFile(file, []byte("keep"), 0o644)
	empty := filepath.Join(dir, "empty")
	os.Mkdir(empty, 0o755)
	link := filepath.Join(dir, "link")
	os.Symlink(empty, link)
	for _, p := range []string{file, empty, link} {
		if code, o, e := runContract("generate", exampleModel, p); code != 2 || o != "" || e == "" {
			t.Errorf("%s: %d %q %q", p, code, o, e)
		}
	}
	if b := mustRead(t, file); string(b) != "keep" {
		t.Fatal("file touched")
	}
	if ents, _ := os.ReadDir(empty); len(ents) != 0 {
		t.Fatal("dir touched")
	}
}
