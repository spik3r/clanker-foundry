const GeneratorVersion = "lifecycle-go/v1"
const ToolchainVersion = "go1.27.3"

func expression(e model.Expr) (string, error) {
	if _, err := model.TypeOf(e); err != nil {
		return "", err
	}
	if e.Kind == "string" {
		return "stringValue{" + strconv.Quote(e.Value) + ",true}", nil
	}
	if e.Kind == "ref" {
		typ, _ := model.TypeOf(e)
		fn := "refString"
		if typ == "uint64" {
			fn = "refUint"
		}
		if typ == "strings" {
			return "task.Acceptance", nil
		}
		return fn + "(" + strconv.Quote(e.Ref) + ",task,command,currentDigest)", nil
	}
	a := make([]string, len(e.Args))
	for i, x := range e.Args {
		v, err := expression(x)
		if err != nil {
			return "", err
		}
		a[i] = v
	}
	switch e.Op {
	case "eq", "ne":
		typ, _ := model.TypeOf(e.Args[0])
		fn := "equalString"
		if typ == "uint64" {
			fn = "equalUint"
		}
		if e.Op == "ne" {
			fn = "notEqualString"
			if typ == "uint64" {
				fn = "notEqualUint"
			}
		}
		return fn + "(" + strings.Join(a, ",") + ")", nil
	case "nonempty":
		typ, _ := model.TypeOf(e.Args[0])
		if typ == "strings" {
			return "(len(" + a[0] + ")>0)", nil
		}
		return "nonempty(" + a[0] + ")", nil
	case "absent":
		return "(!(" + a[0] + ").present)", nil
	case "all":
		return "(" + strings.Join(a, " && ") + ")", nil
	case "any":
		return "(" + strings.Join(a, " || ") + ")", nil
	}
	return "", fmt.Errorf("unsupported expression")
}

// Generate returns code and derived coverage tests. It never writes or executes.
func Generate(input model.Model) (implementation, derivedTests []byte, err error) {
	m, err := model.Normalize(input)
	if err != nil {
		return nil, nil, err
	}
	digest, err := canonical.Digest(m)
	if err != nil {
		return nil, nil, err
	}
	var b strings.Builder
	b.WriteString("// Code generated by " + GeneratorVersion + "; DO NOT EDIT.\npackage lifecycle\n")
	b.WriteString(runtimeSource)
	fmt.Fprintf(&b, "\nconst ModelDigest = %s\nconst ProfileVersion = %s\n", strconv.Quote(digest), strconv.Quote(model.ProfileVersion))
	b.WriteString("func knownState(s State) bool { switch s {")
	for _, s := range m.States {
		fmt.Fprintf(&b, "case %s:return true;", strconv.Quote(s.ID))
	}
	b.WriteString("};return false}\n")
	seen := map[string]bool{}
	b.WriteString("func knownCommand(s string) bool {switch s {")
	for _, t := range m.Transitions {
		if !seen[t.Trigger] {
			fmt.Fprintf(&b, "case %s:return true;", strconv.Quote(t.Trigger))
			seen[t.Trigger] = true
		}
	}
	b.WriteString("};return false}\n")
	for _, g := range m.Guards {
		x, e := expression(g.Expr)
		if e != nil {
			return nil, nil, e
		}
		fmt.Fprintf(&b, "func guard_%s(task Task,command Command,currentDigest string)bool{return %s}\n", g.ID, x)
	}
	b.WriteString("func Transition(task Task,command Command) Result {\nif !validTask(task)||!validCommand(command){return Result{Mode:\"example-only\",Authority:\"none\",ModelDigest:ModelDigest,Refusals:[]string{\"INVALID_INPUT\"}}}\ncurrentDigest,_:=TaskDigest(task)\nvar id string\nfailed:=[]string{}\nswitch {\n")
	for _, t := range m.Transitions {
		fmt.Fprintf(&b, "case task.State==%s && command.Type==%s:\nid=%s\n", strconv.Quote(t.From), strconv.Quote(t.Trigger), strconv.Quote(t.ID))
		for _, g := range t.Guards {
			fmt.Fprintf(&b, "if !guard_%s(task,command,currentDigest){failed=append(failed,%s)}\n", g, strconv.Quote(g))
		}
	}
	b.WriteString("default:return refused(task,\"\",[]string{\"ILLEGAL_TRANSITION\"})}\nif len(failed)>0{return refused(task,id,failed)}\nif task.Revision==math.MaxUint64{return refused(task,id,[]string{\"REVISION_LIMIT\"})}\nnext:=cloneTask(task)\nswitch id {\n")
	for _, t := range m.Transitions {
		fmt.Fprintf(&b, "case %s:\n", strconv.Quote(t.ID))
		for _, e := range t.Effects {
			switch e.Op {
			case model.AssignOwner:
				b.WriteString("if next.Owner==nil{v:=command.Actor;next.Owner=&v}\n")
			case model.SetState:
				fmt.Fprintf(&b, "next.State=%s\n", strconv.Quote(t.To))
			case model.IncrementRevision:
				b.WriteString("next.Revision++\n")
			default:
				return nil, nil, fmt.Errorf("unsupported effect")
			}
		}
	}
	b.WriteString("}\nreturn Result{Mode:\"example-only\",Authority:\"none\",ModelDigest:ModelDigest,OK:true,TransitionID:id,Task:&next,Refusals:[]string{}}\n}\n")
	implementation, err = format.Source([]byte(b.String()))
	if err != nil {
		return nil, nil, err
	}
	derivedTests, err = tests(m)
	return
}
func decision(e model.Expr) string {
	if e.Kind == "op" && e.Op == "eq" && len(e.Args) == 2 {
		a, b := e.Args[0], e.Args[1]
		if a.Kind == "ref" && a.Ref == "review.decision" && b.Kind == "string" {
			return b.Value
		}
		if b.Kind == "ref" && b.Ref == "review.decision" && a.Kind == "string" {
			return a.Value
		}
	}
	for _, a := range e.Args {
		if v := decision(a); v != "" {
			return v
		}
	}
	return ""
}
func tests(m model.Model) ([]byte, error) {
	guards := map[string]model.Guard{}
	for _, g := range m.Guards {
		guards[g.ID] = g
	}
	var b strings.Builder
	b.WriteString("// Code generated from the model: structural edge properties, not success witnesses.\npackage lifecycle\nimport (\"testing\";\"reflect\")\n")
	digest, err := canonical.Digest(m)
	if err != nil {
		return nil, err
	}
	fmt.Fprintf(&b, "func TestModelIdentity(t *testing.T){if ModelDigest != %s {t.Fatal(\"compiled model identity mismatch\")}}\n", strconv.Quote(digest))
	for _, tr := range m.Transitions {
		isReview := false
		dec := "approved"
		for _, id := range tr.Guards {
			e := guards[id].Expr
			if strings.Contains(model.ExprKey(e), "review.") {
				isReview = true
			}
			if v := decision(e); v == "approved" || v == "changesRequested" {
				dec = v
			}
		}
		fmt.Fprintf(&b, "func TestModelPath_%s(t *testing.T){owner:=\"owner\";task:=Task{ID:\"derived-example\",State:%s,Revision:3,Outcome:\"Example outcome\",Acceptance:[]string{\"Example criterion\"},Owner:&owner};command:=Command{Type:%s,Actor:owner,ExpectedRevision:3};\n", tr.ID, strconv.Quote(tr.From), strconv.Quote(tr.Trigger))
		assign := false
		for _, e := range tr.Effects {
			if e.Op == model.AssignOwner {
				assign = true
				b.WriteString("task.Owner=nil;\n")
			}
		}
		if isReview {
			fmt.Fprintf(&b, "d,e:=TaskDigest(task);if e!=nil{t.Fatal(e)};command.Actor=\"reviewer\";command.Review=&Review{TaskID:task.ID,TaskRevision:task.Revision,ModelDigest:ModelDigest,TaskDigest:d,Reviewer:\"reviewer\",Decision:%s};\n", strconv.Quote(dec))
		}
		fmt.Fprintf(&b, "r:=Transition(task,command);if !r.OK {if r.Task==nil||!reflect.DeepEqual(*r.Task,task)||len(r.Refusals)==0{t.Fatalf(\"invalid structural refusal: %%+v\",r)};return};if r.Task==nil||r.TransitionID!=%s||r.Task.State!=%s||r.Task.Revision!=4{t.Fatalf(\"model edge effects drifted: %%+v\",r)};", strconv.Quote(tr.ID), strconv.Quote(tr.To))
		if assign {
			b.WriteString("if r.Task.Owner==nil||*r.Task.Owner!=command.Actor{t.Fatal(\"assignment effect missing\")};")
		}
		b.WriteString("}\n")
	}

	for _, state := range m.States {
		if !state.Terminal {
			continue
		}
		seen := map[string]bool{}
		for _, tr := range m.Transitions {
			if seen[tr.Trigger] {
				continue
			}
			seen[tr.Trigger] = true
			fmt.Fprintf(&b, "func TestModelTerminal_%d_%s_%d_%s(t *testing.T){task:=Task{ID:\"terminal-example\",State:%s,Revision:7,Outcome:\"Outcome\",Acceptance:[]string{\"Criterion\"}};command:=Command{Type:%s,Actor:\"actor\",ExpectedRevision:7};r:=Transition(task,command);if r.OK||r.Task==nil||!reflect.DeepEqual(*r.Task,task)||len(r.Refusals)!=1||r.Refusals[0]!=\"ILLEGAL_TRANSITION\"{t.Fatalf(\"terminal edge admitted: %%+v\",r)}}\n", len(state.ID), state.ID, len(tr.Trigger), tr.Trigger, strconv.Quote(state.ID), strconv.Quote(tr.Trigger))
		}
	}
	return format.Source([]byte(b.String()))
}

