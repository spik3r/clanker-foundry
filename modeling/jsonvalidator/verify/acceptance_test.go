package verify

import (
	"crypto/sha256"
	"encoding/json"
	"fmt"
	"io"
	"os"
	"strings"
	"testing"

	validator "github.com/spik3r/clanker-foundry/modeling/jsonvalidator/testdata/sample"
)

const frozenCorpusSHA256 = "60fb575f37adb783564fbaae7535bf7d59587127dd638c8a0a87ce083d56ef41"

func TestFrozenSyntheticAcceptance(t *testing.T) {
	data, err := os.ReadFile("../testdata/sample/cases.json")
	if err != nil {
		t.Fatal(err)
	}
	if fmt.Sprintf("%x", sha256.Sum256(data)) != frozenCorpusSHA256 {
		t.Fatal("frozen expectations changed")
	}
	var cases []struct {
		ID      string `json:"id"`
		RawJSON string `json:"rawJson"`
		Valid   bool   `json:"valid"`
	}
	if err := json.Unmarshal(data, &cases); err != nil {
		t.Fatal(err)
	}
	if len(cases) != 46 {
		t.Fatal("unexpected case count")
	}
	seen := map[string]bool{}
	validCount := 0
	for _, c := range cases {
		if seen[c.ID] || c.ID == "" {
			t.Fatal("duplicate or empty case ID")
		}
		seen[c.ID] = true
		if c.Valid {
			validCount++
		}
		t.Run(c.ID, func(t *testing.T) {
			d := json.NewDecoder(strings.NewReader(c.RawJSON))
			d.UseNumber()
			var value any
			if err := d.Decode(&value); err != nil {
				t.Fatal(err)
			}
			var trailing any
			if err := d.Decode(&trailing); err != io.EOF {
				t.Fatal("fixture has trailing content")
			}
			if got := validator.Validate(value); got != c.Valid {
				t.Fatalf("got %v, want %v", got, c.Valid)
			}
		})
	}
	if validCount != 12 {
		t.Fatal("unexpected true case count")
	}
	manifestBytes, err := os.ReadFile("../testdata/sample/foundry-manifest.json")
	if err != nil {
		t.Fatal(err)
	}
	var manifest struct {
		Model struct {
			CanonicalSHA256 string `json:"canonicalSHA256"`
		} `json:"model"`
		Files []struct {
			Path   string `json:"path"`
			SHA256 string `json:"sha256"`
		} `json:"files"`
	}
	if err := json.Unmarshal(manifestBytes, &manifest); err != nil {
		t.Fatal(err)
	}
	if validator.ModelSHA256 != manifest.Model.CanonicalSHA256 {
		t.Fatal("generated Go has wrong canonical model pin")
	}
	for _, f := range manifest.Files {
		data, err := os.ReadFile("../testdata/sample/" + f.Path)
		if err != nil || fmt.Sprintf("%x", sha256.Sum256(data)) != f.SHA256 {
			t.Fatalf("manifest does not match %s: %v", f.Path, err)
		}
		if !strings.HasPrefix(string(data), "// Code generated by jsonvalidator 1.0.0 from model "+manifest.Model.CanonicalSHA256+". DO NOT EDIT.\n") {
			t.Fatalf("%s has the wrong generated header", f.Path)
		}
	}
}
