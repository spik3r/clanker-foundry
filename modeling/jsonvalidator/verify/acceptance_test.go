package verify

import (
	"crypto/sha256"
	"encoding/json"
	"fmt"
	"io"
	"os"
	"strings"
	"testing"

	lengths "github.com/spik3r/clanker-foundry/modeling/jsonvalidator/testdata/lengths"
	manifestfx "github.com/spik3r/clanker-foundry/modeling/jsonvalidator/testdata/manifest"
	validator "github.com/spik3r/clanker-foundry/modeling/jsonvalidator/testdata/sample"
)

const frozenCorpusSHA256 = "60fb575f37adb783564fbaae7535bf7d59587127dd638c8a0a87ce083d56ef41"

type fixture struct {
	dir, corpusSHA256 string
	cases, valid      int
	validate          func(any) bool
	modelSHA256       string
}

func TestFrozenSyntheticAcceptance(t *testing.T) {
	for _, f := range []fixture{
		{"sample", frozenCorpusSHA256, 46, 12, validator.Validate, validator.ModelSHA256},
		{"manifest", "22c5346e4f2aecb344431f8bc5f0249e63485379baf61970e90bcbbf148dc889", 52, 10, manifestfx.Validate, manifestfx.ModelSHA256},
		{"lengths", "a1f8df3e54b2802b6f41ce19a2f45147498be51f9c4eab37ed361a208004677f", 50, 25, lengths.Validate, lengths.ModelSHA256},
	} {
		t.Run(f.dir, func(t *testing.T) { runFixture(t, f) })
	}
}

func runFixture(t *testing.T, f fixture) {
	data, err := os.ReadFile("../testdata/" + f.dir + "/cases.json")
	if err != nil {
		t.Fatal(err)
	}
	if fmt.Sprintf("%x", sha256.Sum256(data)) != f.corpusSHA256 {
		t.Fatal("frozen expectations changed")
	}
	var cases []struct {
		ID      string `json:"id"`
		RawJSON string `json:"rawJson"`
		Valid   bool   `json:"valid"`
	}
	if err := json.Unmarshal(data, &cases); err != nil {
		t.Fatal(err)
	}
	if len(cases) != f.cases {
		t.Fatal("unexpected case count")
	}
	seen := map[string]bool{}
	validCount := 0
	for _, c := range cases {
		if seen[c.ID] || c.ID == "" {
			t.Fatal("duplicate or empty case ID")
		}
		seen[c.ID] = true
		if c.Valid {
			validCount++
		}
		t.Run(c.ID, func(t *testing.T) {
			d := json.NewDecoder(strings.NewReader(c.RawJSON))
			d.UseNumber()
			var value any
			if err := d.Decode(&value); err != nil {
				t.Fatal(err)
			}
			var trailing any
			if err := d.Decode(&trailing); err != io.EOF {
				t.Fatal("fixture has trailing content")
			}
			if got := f.validate(value); got != c.Valid {
				t.Fatalf("got %v, want %v", got, c.Valid)
			}
		})
	}
	if validCount != f.valid {
		t.Fatal("unexpected true case count")
	}
	manifestBytes, err := os.ReadFile("../testdata/" + f.dir + "/foundry-manifest.json")
	if err != nil {
		t.Fatal(err)
	}
	var manifest struct {
		Model struct {
			CanonicalSHA256 string `json:"canonicalSHA256"`
		} `json:"model"`
		Files []struct {
			Path   string `json:"path"`
			SHA256 string `json:"sha256"`
		} `json:"files"`
	}
	if err := json.Unmarshal(manifestBytes, &manifest); err != nil {
		t.Fatal(err)
	}
	if f.modelSHA256 != manifest.Model.CanonicalSHA256 {
		t.Fatal("generated Go has wrong canonical model pin")
	}
	for _, mf := range manifest.Files {
		data, err := os.ReadFile("../testdata/" + f.dir + "/" + mf.Path)
		if err != nil || fmt.Sprintf("%x", sha256.Sum256(data)) != mf.SHA256 {
			t.Fatalf("manifest does not match %s: %v", mf.Path, err)
		}
		if !strings.HasPrefix(string(data), "// Code generated by jsonvalidator 1.1.0 from model "+manifest.Model.CanonicalSHA256+". DO NOT EDIT.\n") {
			t.Fatalf("%s has the wrong generated header", mf.Path)
		}
	}
}
